#!/usr/bin/env python
"""Selection signatures: what the papers do not say, recovered from the data.

E92 closed the database side of the provenance question and named the one thing
no VDJdb field records — whether a study pre-selected its TCRs by motif, V gene
or clone size. Reading the methods sections answers it for the open-access
studies (see the E93 log entry) but three of the relevant papers are paywalled
and one is a medRxiv preprint that blocks retrieval.

A selection rule leaves a signature in the deposited data, though, and that is
recoverable for every study including the ones whose text is out of reach. If a
study enriched for a motif, its TCRs are unusually tight in sequence space
relative to other studies working on the same epitope. If it preselected a V
gene, its V usage is unusually concentrated. If it applied a clone-size
threshold, its reported frequencies are left-truncated.

Every signature is computed **against size-matched random subsamples of the
same epitope's cohort**, so cohort-level convergence (which is the thing D
measures and GLCTLVAML is made of) cannot masquerade as a study-level selection
rule. Per E92 the primary snapshot is **2023-06-01**, before the revalidation.

Then the question that matters: does any signature predict the study's
false-positive rate?

Run: .venv/bin/python scripts/84_selection_signatures.py
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import scipy.sparse as sp
from scipy import stats
from scipy.sparse.csgraph import connected_components

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from immrep.data import build_training_frame, load_test  # noqa: E402

REPORT = ROOT / "reports/59_selection_signatures.md"
SNAPSHOT = ROOT / "data/external/vdjdb/vdjdb-2023-06-01/vdjdb_full.txt"
FAMILY_RADIUS = 0.12
MIN_N = 12
DRAWS = 2000
SEED = 0


def entropy(values) -> float:
    """Shannon entropy of a categorical, normalised to [0, 1]."""
    v = pd.Series(values).dropna()
    if len(v) < 2 or v.nunique() < 2:
        return 0.0
    p = v.value_counts(normalize=True).to_numpy()
    return float(-(p * np.log(p)).sum() / np.log(len(v)))


def main() -> int:
    test = load_test().copy()
    labels = build_training_frame()[["tcr_id", "epitope_aa", "pos"]]
    test["_k"] = (test["cdr3_alpha_aa"] + "|" + test["cdr3_beta_aa"] + "|"
                  + test["epitope_aa"])
    scored = labels.dropna(subset=["pos"]).copy()
    scored["pos"] = scored["pos"].astype(int)

    full = pd.read_csv(SNAPSHOT, sep="\t", low_memory=False)
    full = full[(full["species"] == "HomoSapiens")
                & full["cdr3.alpha"].notna() & full["cdr3.beta"].notna()].copy()
    full["_k"] = (full["cdr3.alpha"] + "|" + full["cdr3.beta"] + "|"
                  + full["antigen.epitope"])
    hit = full[full["_k"].isin(set(test["_k"]))].copy()

    # one study per TCR where unambiguous; multi-reference TCRs contribute to each
    pairs = hit[["_k", "reference.id"]].dropna().drop_duplicates()
    frame = test.merge(scored[["tcr_id", "pos"]], on="tcr_id", how="left")
    frame = frame.merge(pairs, on="_k", how="left")
    frame["w"] = 1.0 / frame.groupby("tcr_id")["reference.id"].transform("size")

    cached = np.load(ROOT / "data/interim/sceptr/default.npz", allow_pickle=True)
    V = cached["vectors"]
    V = V / np.linalg.norm(V, axis=1, keepdims=True)
    po = {t: i for i, t in enumerate(cached["tcr_id"])}

    rng = np.random.default_rng(SEED)
    lines = ["# E93 — Selection signatures recovered from the data", "",
             "What the methods sections do not say, and three of them are not",
             "retrievable. Every signature is compared against **size-matched random",
             "subsamples of the same epitope's cohort**, so cohort-level convergence",
             "cannot masquerade as a study-level selection rule. Snapshot",
             "`2023-06-01`, pre-revalidation.",
             "Generated by `scripts/84_selection_signatures.py`.", ""]

    rows = []
    print("=== per (study, epitope): selection signatures vs size-matched nulls ===")
    print(f"  {'study':<30}{'epitope':<11}{'n':>4}{'nn3 z':>8}{'TRBV H z':>10}"
          f"{'TRAV H z':>10}{'fam z':>8}{'excess':>9}")
    for e, coh in test.groupby("epitope_aa"):
        idx = np.array([po[t] for t in coh["tcr_id"]])
        D = 1.0 - V[idx] @ V[idx].T
        np.fill_diagonal(D, np.inf)
        _, fam = connected_components(
            sp.csr_matrix(np.where(np.isinf(D), 1.0, D) <= FAMILY_RADIUS),
            directed=False)
        pos_in = {t: i for i, t in enumerate(coh["tcr_id"])}
        trbv = coh["TRBV_IMGT"].to_numpy()
        trav = coh["TRAV_IMGT"].to_numpy()
        ep_scored = scored[scored["epitope_aa"] == e]
        base = ep_scored["pos"].mean() if len(ep_scored) else np.nan
        sub = frame[(frame["epitope_aa"] == e) & frame["reference.id"].notna()]
        for ref, g in sub.groupby("reference.id"):
            ii = np.array([pos_in[t] for t in g["tcr_id"]])
            n = len(ii)
            if n < MIN_N:
                continue

            def stats_for(sel):
                sub_d = D[np.ix_(sel, sel)]
                k = min(3, len(sel) - 1)
                nn3 = np.sort(sub_d, axis=1)[:, :k].mean()
                return (float(nn3), entropy(trbv[sel]), entropy(trav[sel]),
                        float(pd.Series(fam[sel]).value_counts().iloc[0] / len(sel)))

            obs = stats_for(ii)
            null = np.array([stats_for(rng.choice(len(coh), size=n, replace=False))
                             for _ in range(DRAWS)])
            z = (np.array(obs) - null.mean(0)) / (null.std(0) + 1e-12)
            lab = g[g["pos"].notna()]
            rate = (np.average(lab["pos"], weights=lab["w"])
                    if len(lab) else np.nan)
            excess = rate - base if np.isfinite(rate) else np.nan
            print(f"  {str(ref)[:29]:<30}{e[:10]:<11}{n:4d}{z[0]:+8.2f}{z[1]:+10.2f}"
                  f"{z[2]:+10.2f}{z[3]:+8.2f}"
                  + (f"{excess:+9.3f}" if np.isfinite(excess) else f"{'priv':>9}"))
            rows.append({"ref": str(ref), "epitope": e, "n": n,
                         "z_nn3": z[0], "z_trbv_H": z[1], "z_trav_H": z[2],
                         "z_topfam": z[3], "excess": excess,
                         "split": g["split"].mode().iloc[0]})

    R = pd.DataFrame(rows)
    lines += ["## Per (study, epitope) signatures", "",
              "`nn3 z` — mean distance to the 3 nearest TCRs *within the study*,",
              "standardised against size-matched draws from the same cohort. Negative",
              "means unusually tight, which is what motif-guided enrichment produces.",
              "`TRBV H z` / `TRAV H z` — V-usage entropy; negative means unusually",
              "concentrated. `fam z` — share of the study's TCRs in its single largest",
              "family.", "",
              "| study | epitope | split | n | nn3 z | TRBV H z | TRAV H z | fam z | excess |",
              "|---|---|---|---:|---:|---:|---:|---:|---:|"]
    for _, r in R.sort_values("z_nn3").iterrows():
        ex = f"{r['excess']:+.3f}" if np.isfinite(r["excess"]) else "— (private)"
        lines.append(f"| {r['ref']} | {r['epitope']} | {r['split']} | {int(r['n'])} "
                     f"| {r['z_nn3']:+.2f} | {r['z_trbv_H']:+.2f} "
                     f"| {r['z_trav_H']:+.2f} | {r['z_topfam']:+.2f} | {ex} |")
    lines.append("")

    # ---------- the control that decides whether this is a STUDY effect ----------
    # Convergent TCRs validate better -- that is the project's central per-TCR
    # finding. A study holding more convergent TCRs therefore validates better
    # for a reason that has nothing to do with the study. So the per-TCR
    # density prediction is subtracted before the signature is believed:
    # expected validation is estimated within each epitope from typicality
    # alone, fitted leaving the study out, and the residual excess is what a
    # genuine study effect would move.
    print("\n=== control: subtract what per-TCR typicality already predicts ===")
    typ = {}
    for e, coh in test.groupby("epitope_aa"):
        idx = np.array([po[t] for t in coh["tcr_id"]])
        d = 1.0 - V[idx] @ V[idx].T
        np.fill_diagonal(d, np.inf)
        for i, t in enumerate(coh["tcr_id"]):
            typ[t] = -float(np.sort(d[i])[:8].mean())
    typ = pd.Series(typ)
    lab_all = scored.set_index("tcr_id")["pos"]

    def density_expected(ids, epitope, exclude_ref):
        """Validation rate predicted from typicality alone, fitted on the same
        epitope with this study's TCRs removed, via isotonic regression."""
        from sklearn.isotonic import IsotonicRegression
        other = frame[(frame["epitope_aa"] == epitope)
                      & (frame["reference.id"] != exclude_ref)
                      & frame["pos"].notna()].drop_duplicates("tcr_id")
        if other["pos"].nunique() < 2 or len(other) < 20:
            return np.nan
        iso = IsotonicRegression(increasing="auto", out_of_bounds="clip")
        iso.fit(typ.reindex(other["tcr_id"]).to_numpy(),
                other["pos"].to_numpy().astype(float))
        return float(np.mean(iso.predict(typ.reindex(ids).to_numpy())))

    resid = []
    for _, r in R.iterrows():
        if not np.isfinite(r["excess"]):
            resid.append(np.nan)
            continue
        ids = frame[(frame["epitope_aa"] == r["epitope"])
                    & (frame["reference.id"] == r["ref"])
                    & frame["pos"].notna()]["tcr_id"].unique()
        exp_d = density_expected(ids, r["epitope"], r["ref"])
        obs = float(lab_all.reindex(ids).mean())
        resid.append(obs - exp_d if np.isfinite(exp_d) else np.nan)
    R["excess_resid"] = resid
    print(f"  residual computable for {int(np.isfinite(R['excess_resid']).sum())} "
          f"of {int(R['excess'].notna().sum())} labelled cells")

    # ---------- does any signature predict the false-positive rate? ----------
    print("\n=== does any selection signature predict the false-positive rate? ===")
    lab = R[R["excess"].notna()]
    print(f"  {len(lab)} labelled (study, epitope) cells")
    labr = R[R["excess_resid"].notna()]
    print(f"  {'signature':<14}{'rho w/ excess':>15}{'p':>9}"
          f"{'rho w/ RESIDUAL':>18}{'p':>9}")
    sig_rows = []
    for col in ("z_nn3", "z_trbv_H", "z_trav_H", "z_topfam"):
        out = []
        for frm, ycol in ((lab, "excess"), (labr, "excess_resid")):
            rho = stats.spearmanr(frm[col], frm[ycol]).statistic
            obs = abs(rho)
            cnt = sum(abs(stats.spearmanr(
                frm[col], rng.permutation(frm[ycol].to_numpy())).statistic)
                >= obs - 1e-12 for _ in range(20000))
            out += [rho, (cnt + 1) / 20001]
        print(f"  {col:<14}{out[0]:+15.3f}{out[1]:9.4f}{out[2]:+18.3f}{out[3]:9.4f}")
        sig_rows.append([col] + out)

    lines += ["## Does any signature predict the false-positive rate?", "",
              f"{len(lab)} labelled (study, epitope) cells, exact permutation p.", "",
              "`excess` is the raw study effect; `residual` subtracts what each",
              "TCR's own typicality already predicts, fitted within the epitope with",
              "that study held out. Only the residual column is a *study* effect.", "",
              "| signature | ρ with excess | p | ρ with residual | p |",
              "|---|---:|---:|---:|---:|"]
    for r in sig_rows:
        lines.append(f"| `{r[0]}` | {r[1]:+.3f} | {r[2]:.4f} "
                     f"| **{r[3]:+.3f}** | **{r[4]:.4f}** |")
    lines.append("")

    # ---------- who built the large public families? ----------
    print("\n=== who built the large public families? ===")
    fam_rows = []
    for e in ("GILGFVFTL", "GLCTLVAML", "NLVPMVATV", "YLQPRTFLL", "TTDPSFLGRY"):
        coh = test[test["epitope_aa"] == e]
        idx = np.array([po[t] for t in coh["tcr_id"]])
        D = 1.0 - V[idx] @ V[idx].T
        _, fam = connected_components(sp.csr_matrix(D <= FAMILY_RADIUS),
                                      directed=False)
        sizes = pd.Series(fam).value_counts()
        for f in sizes[sizes >= 10].index[:3]:
            ids = coh["tcr_id"].to_numpy()[fam == f]
            g = frame[frame["tcr_id"].isin(ids) & frame["reference.id"].notna()]
            if g.empty:
                continue
            share = g.groupby("reference.id")["w"].sum()
            share = share / share.sum()
            top = share.sort_values(ascending=False)
            lp = scored[scored["tcr_id"].isin(ids)]["pos"]
            print(f"  {e} family size {int(sizes[f])}: refs {len(share)}, "
                  f"top {top.iloc[0]:.0%} ({str(top.index[0])[:34]}), "
                  f"validated {lp.mean():.2f}" if len(lp) else "")
            fam_rows.append([e, int(sizes[f]), len(share), float(top.iloc[0]),
                             str(top.index[0]),
                             float(lp.mean()) if len(lp) else np.nan])

    lines += ["## Who built the large public families?", "",
              "If one study supplied a family, that family could be its selection",
              "rule rather than a biological convergence. E54/E57 answered this with",
              "donors; this answers it with references.", "",
              "| epitope | family size | refs | largest share | that study | validated |",
              "|---|---:|---:|---:|---|---:|"]
    for r in fam_rows:
        v = f"{r[5]:.2f}" if np.isfinite(r[5]) else "—"
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | **{r[3]:.0%}** | {r[4]} | {v} |")
    lines.append("")

    REPORT.write_text("\n".join(lines) + "\n")
    print(f"\nwrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
