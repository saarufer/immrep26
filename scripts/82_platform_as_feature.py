#!/usr/bin/env python
"""Can the sequencing platform be used as a discriminative feature?

E90 found that the sequencing platform is the one study-level attribute that
survives the collinearity check: `sanger` spans 12 studies and validates 0.090
below its epitope-matched expectation, `amplicon-seq` spans 9 and validates
0.169 above, both at permutation p < 0.0005. That is a population-level
statement. Turning it into a feature requires three separate things to be true,
and they are tested in the order that can close the question earliest.

  1. **Availability.** Is the field populated on the private rows at all?
  2. **Variation within an epitope.** The metric is mean per-epitope ROC AUC, so
     a feature that is *constant inside a cohort* contributes exactly zero to it
     — it cannot reorder anything. This is the gate that matters most and it is
     easy to overlook, because a feature can look strongly predictive in a
     pooled analysis and still be worthless under a within-epitope metric.
  3. **Ranking power where it does vary.** Even if (1) and (2) fail on the
     private split, measuring the counterfactual on the public epitopes says
     whether the mechanism is real at the level of ranking individual TCRs
     rather than comparing study populations. If it is worthless even there,
     the question is closed twice.

A second route is also tested: rather than the platform, the **study's own
measured false-positive rate**, estimated on the public epitopes and carried to
the private rows through any study that contributes to both.

Run: .venv/bin/python scripts/82_platform_as_feature.py
"""

from __future__ import annotations

import importlib.util
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from immrep.data import build_training_frame, load_test  # noqa: E402

REPORT = ROOT / "reports/57_platform_as_feature.md"
VDJDB = ROOT / "data/external/vdjdb/vdjdb-2026-06-03/vdjdb_full.txt"
STRUCTURE_WEIGHT = 0.3


def load_module(name: str, path: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def main() -> int:
    test = load_test()
    labels = build_training_frame()[["tcr_id", "epitope_aa", "pos"]]
    hyp = load_module("hyp", "scripts/40_new_hypotheses.py")
    decomp = load_module("decomp", "scripts/20_auc_error_decomposition.py")

    test = test.copy()
    test["_k"] = (test["cdr3_alpha_aa"] + "|" + test["cdr3_beta_aa"] + "|"
                  + test["epitope_aa"])
    full = pd.read_csv(VDJDB, sep="\t", low_memory=False)
    full = full[(full["species"] == "HomoSapiens")
                & full["cdr3.alpha"].notna() & full["cdr3.beta"].notna()].copy()
    full["_k"] = (full["cdr3.alpha"] + "|" + full["cdr3.beta"] + "|"
                  + full["antigen.epitope"])
    hit = full[full["_k"].isin(set(test["_k"]))].copy()

    # One platform per key. A key with several records can disagree; take the
    # modal non-null value and count how often that happens.
    def modal(series):
        s = series.dropna().astype(str).str.strip()
        s = s[s != ""]
        return s.mode().iloc[0] if len(s) else None

    plat = hit.groupby("_k")["method.sequencing"].agg(modal)
    conflict = hit.groupby("_k")["method.sequencing"].nunique(dropna=True)
    test["platform"] = test["_k"].map(plat)
    print(f"keys with conflicting platforms across records: "
          f"{int((conflict > 1).sum())} of {conflict.size}")

    lines = ["# E91 — Can the sequencing platform be a discriminative feature?", "",
             "E90 found the platform is the one study attribute surviving the",
             "collinearity check. That is a population-level result; this asks",
             "whether it can rank individual TCRs.",
             "Generated by `scripts/82_platform_as_feature.py`.", ""]

    # ---------- 1 & 2. availability and within-epitope variation ----------
    print("\n=== 1-2. availability and within-epitope variation ===")
    print(f"  {'epitope':<12}{'split':<9}{'rows':>6}{'populated':>11}"
          f"{'levels':>8}  composition")
    avail = []
    for e, g in test.groupby("epitope_aa"):
        sp = g["split"].mode().iloc[0]
        v = g["platform"]
        comp = v.dropna().value_counts(normalize=True)
        cs = "  ".join(f"{k} {p:.0%}" for k, p in comp.items()) if len(comp) else "--"
        print(f"  {e:<12}{sp:<9}{len(g):6d}{int(v.notna().sum()):11d}"
              f"{comp.size:8d}  {cs}")
        avail.append([e, sp, len(g), int(v.notna().sum()), int(comp.size), cs])

    lines += ["## 1–2. Availability and within-epitope variation", "",
              "The metric is **mean per-epitope ROC AUC**, so a feature that is",
              "constant inside a cohort contributes exactly zero — it cannot reorder",
              "anything, however predictive it looks pooled across epitopes.", "",
              "| epitope | split | rows | platform populated | levels | composition |",
              "|---|---|---:|---:|---:|---|"]
    for r in avail:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | **{r[4]}** | {r[5]} |")
    priv_var = [r for r in avail if r[1] == "private" and r[4] > 1]
    lines += ["",
              f"**Private epitopes where the platform varies at all: "
              f"{len(priv_var)} of 3.**", ""]

    # ---------- 3. the counterfactual on the public epitopes ----------
    print("\n=== 3. the counterfactual: does it rank, where it does vary? ===")
    scored = labels.dropna(subset=["pos"]).copy()
    scored["pos"] = scored["pos"].astype(int)
    pf = test.set_index("tcr_id")["platform"]
    # Score each level by its validation rate on the OTHER public epitopes, so
    # the feature is never fitted on the epitope it is scored on.
    pub = scored.merge(test[["tcr_id", "platform"]], on="tcr_id")
    rows, per_ep = [], {}
    for e in sorted(pub["epitope_aa"].unique()):
        rest = pub[pub["epitope_aa"] != e]
        rate = rest.groupby("platform")["pos"].mean()
        here = pub[pub["epitope_aa"] == e]
        s = here["platform"].map(rate)
        if here["platform"].nunique(dropna=True) < 2 or s.isna().all():
            per_ep[e] = np.nan
            print(f"  {e:<12} platform constant or absent -> contributes nothing")
            rows.append([e, int(here['platform'].nunique(dropna=True)), np.nan])
            continue
        s = s.fillna(rest["pos"].mean())
        auc = float(__import__("sklearn.metrics", fromlist=["x"])
                    .roc_auc_score(here["pos"], s))
        per_ep[e] = auc
        print(f"  {e:<12} levels {here['platform'].nunique(dropna=True)}  "
              f"leave-epitope-out AUC {auc:.4f}")
        rows.append([e, int(here["platform"].nunique(dropna=True)), auc])
    usable = [v for v in per_ep.values() if np.isfinite(v)]
    print(f"\n  macro over the {len(usable)} epitopes where it varies: "
          f"{np.mean(usable):.4f}   (chance 0.5)")

    lines += ["## 3. The counterfactual: does it rank where it does vary?", "",
              "Each level is scored by its validation rate on the **other** public",
              "epitopes, so the feature is never fitted on the epitope it is scored",
              "on.", "", "| epitope | levels | leave-epitope-out AUC |",
              "|---|---:|---:|"]
    for r in rows:
        lines.append(f"| {r[0]} | {r[1]} | "
                     + (f"{r[2]:.4f}" if np.isfinite(r[2]) else "— (constant)") + " |")
    lines += ["",
              f"Macro over the {len(usable)} epitopes where it varies: "
              f"**{np.mean(usable):.4f}** against chance 0.5.", ""]

    # blend with D, to price it even at its best
    d = pd.read_csv(ROOT / "submissions/d_density3_m30pool_m50_struct.csv"
                    ).set_index("tcr_id")["prediction"]
    feat = pd.Series(index=test["tcr_id"], dtype=float)
    overall = pub.groupby("platform")["pos"].mean()
    feat.loc[:] = test.set_index("tcr_id")["platform"].map(overall).reindex(feat.index)
    feat = feat.fillna(pub["pos"].mean())
    featr = hyp.rank_within(feat, test)
    print(f"\n  D alone                     {hyp.mean_auc(labels, d):.4f}")
    blend_rows = []
    for w in (0.05, 0.10, 0.20, 0.30):
        b = (1 - w) * d + w * featr
        v = hyp.mean_auc(labels, b)
        print(f"  D + platform at w={w:<5.2f}      {v:.4f}   "
              f"{v - hyp.mean_auc(labels, d):+.4f}")
        blend_rows.append([w, v, v - hyp.mean_auc(labels, d)])
    lines += ["Blended into D (platform scored on all public rows, i.e. the",
              "most favourable possible fitting):", "",
              "| structure of blend | macro | vs D |", "|---|---:|---:|",
              f"| D alone | {hyp.mean_auc(labels, d):.4f} | — |"]
    for r in blend_rows:
        lines.append(f"| D + platform, w={r[0]:.2f} | {r[1]:.4f} | {r[2]:+.4f} |")
    lines.append("")

    # ---------- 4. the study-quality route ----------
    print("\n=== 4. the other route: a study's own measured false-positive rate ===")
    j = hit[["_k", "reference.id", "antigen.epitope"]].drop_duplicates()
    sp_of = test.drop_duplicates("epitope_aa").set_index("epitope_aa")["split"].to_dict()
    j["split"] = j["antigen.epitope"].map(sp_of)
    spans = j.groupby("reference.id")["split"].agg(lambda s: frozenset(s))
    both = [r for r, v in spans.items() if {"public", "private"} <= set(v)]
    print(f"  references contributing to BOTH public and private epitopes: "
          f"{len(both)}")
    # A handful of keys carry more than one tcr_id, so collapse to the mean
    # rather than reindexing on a duplicated axis.
    key_pos = (scored.merge(test[["tcr_id", "_k"]], on="tcr_id")
               .groupby("_k")["pos"].mean())
    span_rows = []
    for r in both:
        sub = j[j["reference.id"] == r]
        parts = []
        for e in sorted(sub["antigen.epitope"].unique()):
            n = int((sub["antigen.epitope"] == e).sum())
            if sp_of[e] == "public":
                ks = sub[sub["antigen.epitope"] == e]["_k"]
                rate = key_pos.reindex(ks).dropna()
                base = scored[scored["epitope_aa"] == e]["pos"].mean()
                parts.append(f"{e}({n}, {rate.mean():.2f} vs base {base:.2f})")
            else:
                parts.append(f"**{e}({n}, PRIVATE)**")
        print(f"  {r[:48]:<50} " + " | ".join(p.replace('**', '')
                                              for p in parts))
        span_rows.append([r, parts])

    lines += ["## 4. The other route: a study's measured false-positive rate", "",
              "Rather than the platform, carry a study's *own* public validation",
              f"rate to the private rows. Only **{len(both)}** references contribute",
              "to both sides:", ""]
    for r, parts in span_rows:
        lines.append(f"- `{r}` — " + " | ".join(parts))
    lines.append("")

    REPORT.write_text("\n".join(lines) + "\n")
    print(f"\nwrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
