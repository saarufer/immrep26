#!/usr/bin/env python
"""Which prior studies contributed the annotations that failed revalidation?

Every TCR-epitope pair in this competition came from somewhere: a published
screen, a tetramer sort, a 10x dextramer panel. The competition label is the
outcome of **re-testing** those annotations, so `pos = 0` is, to a first
approximation, a false positive in the prior literature. That makes a question
available that no amount of model tuning can answer: **do some studies produce
more false positives than others, and if so, what distinguishes them?**

This is not the provenance question E56 asked. E56 asked whether distinct
donors could be resolved, in order to decide whether convergent families were a
citation artifact. And it is not the "can metadata predict validation" question
either, which was settled negatively on the private split. This asks about data
quality in the source literature, and it is worth answering whether or not it
moves a score.

**The confound that dominates and must be removed first** is the epitope. Base
validation rates run from 0.287 on NLVPMVATV to 0.663 on GILGFVFTL, and studies
specialise — a CMV paper contributes NLVPMVATV, a SARS-CoV-2 paper contributes
YLQPRTFLL. Comparing raw study rates would mostly rediscover which epitope each
group worked on. Every comparison below is therefore made against the epitope's
own base rate, computed **leaving that study out** so a large contributor is not
compared against a mean it defines.

**Attribution.** 1,777 of the 1,782 scorable rows match a VDJdb record;
**1,615** carry exactly one reference and form the primary analysis, where
attribution is unambiguous. The 162 multi-reference TCRs are analysed
separately, since "reported by more than one independent study" is itself a
candidate quality signal.

Three parts: is the between-study variation real (against a permutation null),
which studies are the outliers, and which method attributes explain it.

Run: .venv/bin/python scripts/81_study_false_positive_rate.py
"""

from __future__ import annotations

import re
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from immrep.data import build_training_frame, load_test  # noqa: E402

REPORT = ROOT / "reports/56_study_false_positive_rate.md"
VDJDB = ROOT / "data/external/vdjdb/vdjdb-2026-06-03/vdjdb_full.txt"
MIN_N = 10          # a (study, epitope) cell must hold this many TCRs
PERMUTATIONS = 20_000
SEED = 0
ATTRIBUTES = ["method.identification", "method.singlecell", "method.sequencing",
              "meta.cell.subset", "meta.tissue", "vdjdb.score"]


def short(ref: str) -> str:
    """A readable label: PMID number, or the host of a URL."""
    if ref.startswith("PMID:"):
        return ref
    m = re.search(r"(10\.\d{4,}/[^\s/]+)", ref)
    if m:
        return "doi:" + m.group(1)
    m = re.search(r"https?://(?:www\.)?([^/]+)", ref)
    return (m.group(1) if m else ref)[:40]


def main() -> int:
    test = load_test()
    labels = build_training_frame()[["tcr_id", "epitope_aa", "pos"]]
    m = test.merge(labels[["tcr_id", "pos"]], on="tcr_id")
    m = m[m["pos"].notna()].copy()
    m["pos"] = m["pos"].astype(int)
    m["_k"] = m["cdr3_alpha_aa"] + "|" + m["cdr3_beta_aa"] + "|" + m["epitope_aa"]

    full = pd.read_csv(VDJDB, sep="\t", low_memory=False)
    full = full[(full["species"] == "HomoSapiens")
                & full["cdr3.alpha"].notna() & full["cdr3.beta"].notna()].copy()
    full["_k"] = (full["cdr3.alpha"] + "|" + full["cdr3.beta"] + "|"
                  + full["antigen.epitope"])
    hit = full[full["_k"].isin(set(m["_k"]))].copy()

    n_ref = hit.groupby("_k")["reference.id"].nunique()
    single = set(n_ref[n_ref == 1].index)
    print(f"{len(m)} scorable rows; {m['_k'].nunique()} distinct keys; "
          f"{len(single)} single-reference, {int((n_ref > 1).sum())} multi")

    lines = ["# E90 — Which prior studies contributed the false positives?", "",
             "The competition label is the outcome of **re-testing** a published",
             "annotation, so `pos = 0` is approximately a false positive in the",
             "source literature. Generated by",
             "`scripts/81_study_false_positive_rate.py`.", ""]

    # ---------- 0. does replication predict validation? ----------
    print("\n=== 0. does being reported by more than one study predict validation? ===")
    lab_by_key = m.drop_duplicates("_k").set_index("_k")[["pos", "epitope_aa"]]
    rep = pd.DataFrame({"n_ref": n_ref}).join(lab_by_key)
    print(f"  {'epitope':<12}{'1 ref: n':>10}{'val rate':>10}"
          f"{'>1 ref: n':>11}{'val rate':>10}{'diff':>9}")
    rep_rows = []
    for e, g in rep.groupby("epitope_aa"):
        a, b = g[g.n_ref == 1], g[g.n_ref > 1]
        if len(b) < 5:
            print(f"  {e:<12}{len(a):10d}{a.pos.mean():10.3f}{len(b):11d}"
                  f"{'--':>10}{'':>9}")
            rep_rows.append([e, len(a), a.pos.mean(), len(b), np.nan, np.nan])
            continue
        print(f"  {e:<12}{len(a):10d}{a.pos.mean():10.3f}{len(b):11d}"
              f"{b.pos.mean():10.3f}{b.pos.mean()-a.pos.mean():+9.3f}")
        rep_rows.append([e, len(a), a.pos.mean(), len(b), b.pos.mean(),
                         b.pos.mean() - a.pos.mean()])
    # Mantel-Haenszel style pooled test, epitope-stratified
    tbl = np.array([[[int(((rep.epitope_aa == e) & (rep.n_ref > 1) & (rep.pos == v)).sum()),
                      int(((rep.epitope_aa == e) & (rep.n_ref == 1) & (rep.pos == v)).sum())]
                     for v in (1, 0)] for e in sorted(rep.epitope_aa.unique())])
    num = sum(t[0, 0] * t[1, 1] / t.sum() for t in tbl if t.sum() > 0)
    den = sum(t[0, 1] * t[1, 0] / t.sum() for t in tbl if t.sum() > 0)
    print(f"  Mantel-Haenszel odds ratio (epitope-stratified): {num/den:.3f}")
    lines += ["## 0. Does replication across studies predict validation?", "",
              "| epitope | 1 reference | rate | >1 reference | rate | difference |",
              "|---|---:|---:|---:|---:|---:|"]
    for r in rep_rows:
        b = f"{r[4]:.3f}" if np.isfinite(r[4]) else "--"
        d = f"{r[5]:+.3f}" if np.isfinite(r[5]) else ""
        lines.append(f"| {r[0]} | {r[1]} | {r[2]:.3f} | {r[3]} | {b} | {d} |")
    lines += ["",
              f"Epitope-stratified Mantel-Haenszel odds ratio: **{num/den:.3f}**.", ""]

    # ---------- 0b. is the replication signal usable? ----------
    # An odds ratio of that size demands two checks before it means anything:
    # does the quantity exist on the private rows at all, and is it just
    # typicality wearing a citation count?
    print("\n=== 0b. is the replication signal available, and is it new? ===")
    allk = test.copy()
    allk["_k"] = (allk["cdr3_alpha_aa"] + "|" + allk["cdr3_beta_aa"] + "|"
                  + allk["epitope_aa"])
    nref_all = (full[full["_k"].isin(set(allk["_k"]))]
                .groupby("_k")["reference.id"].nunique())
    allk["n_ref"] = allk["_k"].map(nref_all).fillna(0)
    print(f"  {'epitope':<12}{'split':<9}{'rows':>6}{'matched':>9}"
          f"{'>1 ref':>8}{'share':>8}")
    avail = []
    for e, g in allk.groupby("epitope_aa"):
        sp = g["split"].mode().iloc[0]
        print(f"  {e:<12}{sp:<9}{len(g):6d}{int((g.n_ref > 0).sum()):9d}"
              f"{int((g.n_ref > 1).sum()):8d}{(g.n_ref > 1).mean():8.1%}")
        avail.append([e, sp, len(g), int((g.n_ref > 0).sum()),
                      int((g.n_ref > 1).sum()), float((g.n_ref > 1).mean())])

    cached = np.load(ROOT / "data/interim/sceptr/default.npz", allow_pickle=True)
    W = cached["vectors"]
    W = W / np.linalg.norm(W, axis=1, keepdims=True)
    po = {t: i for i, t in enumerate(cached["tcr_id"])}
    typ = {}
    for e, g in allk.groupby("epitope_aa"):
        blk = W[[po[t] for t in g["tcr_id"]]]
        d = 1.0 - blk @ blk.T
        np.fill_diagonal(d, np.inf)
        for i, t in enumerate(g["tcr_id"]):
            typ[t] = -float(np.sort(d[i])[:8].mean())
    typ = pd.Series(typ)
    nref_s = allk.set_index("tcr_id")["n_ref"]
    # n_ref is constant (all zero) inside some cohorts, where the correlation
    # is undefined rather than zero -- average only over cohorts where it varies.
    varying = [(e, g) for e, g in allk.groupby("epitope_aa")
               if g["n_ref"].nunique() > 1]
    rhos = [stats.spearmanr(nref_s.reindex(g["tcr_id"]),
                            typ.reindex(g["tcr_id"])).statistic
            for _, g in varying]
    rho = float(np.mean(rhos))
    print(f"\n  within-epitope Spearman(n_ref, typicality) = {rho:+.3f}  "
          f"(over the {len(varying)} cohorts where n_ref varies at all)")
    for (e, _), r in zip(varying, rhos):
        print(f"    {e:<12}{r:+.3f}")
    print("  (the typicality gate is 0.6378 -- above it the feature is "
          "re-encoding density)")

    lines += ["### 0b. Is the replication signal usable?", "",
              "An odds ratio that size needs two checks: does the quantity exist on",
              "the private rows, and is it just typicality wearing a citation count?",
              "", "| epitope | split | rows | matched in VDJdb | >1 reference | share |",
              "|---|---|---:|---:|---:|---:|"]
    for r in avail:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]:.1%} |")
    lines += ["",
              f"Within-epitope Spearman(n_ref, typicality) = **{rho:+.3f}** over",
              f"the {len(varying)} cohorts where `n_ref` varies at all, against a",
              "`typicality_gate` of 0.6378.", ""]

    # ---------- the primary frame: one row per single-reference TCR ----------
    s = hit[hit["_k"].isin(single)].drop_duplicates("_k").set_index("_k")
    prim = lab_by_key.loc[sorted(single)].join(
        s[["reference.id"] + ATTRIBUTES])
    prim["ref"] = prim["reference.id"].map(short)
    base = prim.groupby("epitope_aa")["pos"].agg(["size", "mean"])
    print("\n=== epitope base rates among single-reference TCRs ===")
    print(base.to_string())

    # ---------- 1. is between-study variation beyond chance? ----------
    cells = (prim.groupby(["ref", "epitope_aa"])["pos"]
             .agg(n="size", k="sum").reset_index())
    cells = cells[cells["n"] >= MIN_N].copy()
    print(f"\n=== 1. is the between-study variation real? ===")
    print(f"  {len(cells)} (study, epitope) cells with n >= {MIN_N}, "
          f"{cells['ref'].nunique()} studies, {cells['n'].sum()} TCRs")

    def loo_expected(frame):
        """Epitope base rate with the cell's own study removed."""
        out = []
        for _, r in frame.iterrows():
            rest = prim[(prim.epitope_aa == r["epitope_aa"]) & (prim.ref != r["ref"])]
            out.append(rest["pos"].mean() if len(rest) else np.nan)
        return np.array(out)

    cells["expected"] = loo_expected(cells)
    cells["observed"] = cells["k"] / cells["n"]
    cells["excess"] = cells["observed"] - cells["expected"]
    # chi-square style dispersion statistic against the leave-one-out expectation
    def dispersion(k, n, p):
        return float(np.sum((k - n * p) ** 2 / (n * p * (1 - p))))
    stat = dispersion(cells["k"].to_numpy(), cells["n"].to_numpy(),
                      cells["expected"].to_numpy())
    rng = np.random.default_rng(SEED)
    null = np.empty(PERMUTATIONS)
    perm_src = {e: prim[prim.epitope_aa == e]["pos"].to_numpy()
                for e in prim.epitope_aa.unique()}
    for i in range(PERMUTATIONS):
        ks = []
        for _, r in cells.iterrows():
            pool = perm_src[r["epitope_aa"]]
            ks.append(rng.choice(pool, size=int(r["n"]), replace=False).sum())
        null[i] = dispersion(np.array(ks), cells["n"].to_numpy(),
                             cells["expected"].to_numpy())
        if i >= 1999:            # 2000 is ample; the statistic is far out
            null = null[:2000]
            break
    p_disp = float((null >= stat).mean())
    print(f"  dispersion statistic {stat:.1f} against {len(cells)} cells")
    print(f"  permutation null: mean {null.mean():.1f}, 95th pct "
          f"{np.percentile(null, 95):.1f}, max {null.max():.1f}")
    print(f"  p = {p_disp:.4f}  ->  between-study variation is "
          f"{'REAL' if p_disp < 0.05 else 'not distinguishable from chance'}")

    lines += ["## 1. Is the between-study variation real?", "",
              f"{len(cells)} (study, epitope) cells with n >= {MIN_N}, covering",
              f"{cells['ref'].nunique()} studies and {cells['n'].sum()} TCRs. Each cell",
              "is compared against its epitope's base rate computed **with that study",
              "removed**, and the null shuffles labels within each epitope.", "",
              f"- dispersion statistic **{stat:.1f}**",
              f"- permutation null: mean {null.mean():.1f}, "
              f"95th percentile {np.percentile(null, 95):.1f}, max {null.max():.1f}",
              f"- **p = {p_disp:.4f}**", ""]

    # ---------- 2. which studies are the outliers? ----------
    cells["z"] = ((cells["k"] - cells["n"] * cells["expected"])
                  / np.sqrt(cells["n"] * cells["expected"] * (1 - cells["expected"])))
    cells["ci"] = [stats.binomtest(int(k), int(n)).proportion_ci(0.95)
                   for k, n in zip(cells["k"], cells["n"])]
    show = cells.sort_values("z")
    print(f"\n=== 2. the per-study table, worst first ===")
    print(f"  {'study':<34}{'epitope':<12}{'n':>5}{'validated':>11}"
          f"{'expected':>10}{'excess':>9}{'z':>7}")
    for _, r in show.iterrows():
        print(f"  {r['ref'][:33]:<34}{r['epitope_aa'][:11]:<12}{int(r['n']):5d}"
              f"{r['observed']:11.3f}{r['expected']:10.3f}{r['excess']:+9.3f}"
              f"{r['z']:+7.2f}")

    lines += ["## 2. The per-study table, worst first", "",
              "`excess` is the validation rate minus the epitope's leave-this-study-out",
              "base rate. Negative means this study's annotations failed re-testing",
              "more often than the rest of the field's on the same epitope.", "",
              "| study | epitope | n | validated | expected | excess | z |",
              "|---|---|---:|---:|---:|---:|---:|"]
    for _, r in show.iterrows():
        lines.append(f"| {r['ref']} | {r['epitope_aa']} | {int(r['n'])} "
                     f"| {r['observed']:.3f} | {r['expected']:.3f} "
                     f"| {r['excess']:+.3f} | {r['z']:+.2f} |")
    lines.append("")

    # ---------- 3. what explains it? ----------
    print(f"\n=== 3. which method attributes explain the excess? ===")
    print("  Each attribute level is compared against the epitope-matched")
    print("  expectation over all other levels, so the epitope mix is held fixed.")
    attr_rows = []

    def matched_contrast(sel: np.ndarray):
        """Observed minus epitope-matched expectation for a boolean subset.

        Restricted to epitopes where BOTH the subset and its complement are
        non-empty -- otherwise the 'expectation' for a level that monopolises an
        epitope is undefined, which is what produced NaNs in the first draft.
        """
        eps_ok = [e for e in base.index
                  if (ep_arr[sel] == e).any() and (ep_arr[~sel] == e).any()]
        if not eps_ok:
            return None
        keep = np.isin(ep_arr, eps_ok)
        sub, comp = sel & keep, (~sel) & keep
        w = {e: float((ep_arr[sub] == e).mean()) for e in eps_ok}
        exp = sum(w[e] * y_arr[comp & (ep_arr == e)].mean() for e in eps_ok)
        return float(y_arr[sub].mean()), float(exp), int(sub.sum()), eps_ok

    ep_arr = prim["epitope_aa"].to_numpy()
    y_arr = prim["pos"].to_numpy().astype(float)

    for attr in ATTRIBUTES:
        vals = prim[attr].fillna("(missing)").astype(str).str.strip().to_numpy()
        counts = pd.Series(vals).value_counts()
        keep_levels = counts[counts >= 25].index
        if len(keep_levels) < 2:
            print(f"\n  {attr}: fewer than two levels with n >= 25, skipped")
            continue
        print(f"\n  {attr}")
        print(f"  {'level':<34}{'n':>6}{'validated':>11}{'expected':>10}"
              f"{'excess':>9}{'p':>8}  epitopes")
        for v in keep_levels:
            sel = vals == v
            got = matched_contrast(sel)
            if got is None:
                print(f"  {str(v)[:33]:<34}{int(sel.sum()):6d}"
                      f"{'  -- monopolises every epitope it appears in':<40}")
                continue
            obs, exp, n_used, eps_ok = got
            # Permute membership WITHIN each epitope, recomputing both sides.
            cnt = 0
            for _ in range(2000):
                perm = np.zeros(len(sel), dtype=bool)
                for e in base.index:
                    idx = np.where(ep_arr == e)[0]
                    k = int(sel[idx].sum())
                    if k:
                        perm[rng.choice(idx, size=k, replace=False)] = True
                g = matched_contrast(perm)
                if g is not None and abs(g[0] - g[1]) >= abs(obs - exp) - 1e-12:
                    cnt += 1
            pv = (cnt + 1) / 2001
            print(f"  {str(v)[:33]:<34}{n_used:6d}{obs:11.3f}{exp:10.3f}"
                  f"{obs-exp:+9.3f}{pv:8.3f}  {len(eps_ok)}")
            attr_rows.append([attr, str(v), n_used, obs, exp, obs - exp, pv,
                              len(eps_ok)])

    # ---------- 3b. how much of part 3 is just the study? ----------
    # Each study generally uses one method, so an attribute level carried by a
    # single study is indistinguishable from that study. Count the studies
    # behind each level before reading any of part 3 as a method effect.
    print("\n=== 3b. how many distinct studies stand behind each level? ===")
    print(f"  {'attribute':<24}{'level':<22}{'n':>6}{'studies':>9}"
          f"{'top study share':>17}")
    collin = []
    for attr in ATTRIBUTES:
        vals = prim[attr].fillna("(missing)").astype(str).str.strip()
        for v, cnt in vals.value_counts().items():
            if cnt < 25:
                continue
            refs = prim.loc[vals == v, "ref"]
            top = refs.value_counts(normalize=True).iloc[0]
            print(f"  {attr:<24}{str(v)[:21]:<22}{cnt:6d}{refs.nunique():9d}"
                  f"{top:17.1%}")
            collin.append([attr, str(v), int(cnt), int(refs.nunique()), float(top)])

    lines += ["### 3b. How much of part 3 is just the study?", "",
              "Each study generally uses one method, so a level carried by one study",
              "is indistinguishable from that study. Read part 3 only for levels",
              "spanning several studies with no dominant one.", "",
              "| attribute | level | n | distinct studies | largest study's share |",
              "|---|---|---:|---:|---:|"]
    for r in collin:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]:.1%} |")
    lines.append("")

    # ---------- 3c. is it the era rather than the method? ----------
    # sanger vs amplicon-seq is also a proxy for when the work was done. PMIDs
    # are close enough to monotonic in time to serve as a recency ordinal.
    print("\n=== 3c. is it the era rather than the method? ===")
    with_pmid = cells[cells["ref"].str.startswith("PMID:")].copy()
    with_pmid["pmid"] = with_pmid["ref"].str.replace("PMID:", "").astype(int)
    r_era = stats.spearmanr(with_pmid["pmid"], with_pmid["z"]).statistic
    obs = abs(r_era)
    cnt = sum(abs(stats.spearmanr(
        with_pmid["pmid"], rng.permutation(with_pmid["z"].to_numpy())).statistic)
        >= obs - 1e-12 for _ in range(20000))
    p_era = (cnt + 1) / 20001
    print(f"  {len(with_pmid)} (study, epitope) cells carry a PMID")
    print(f"  Spearman(PMID as recency, excess z) = {r_era:+.3f}, "
          f"permutation p = {p_era:.4f}")
    seq_era = (prim[prim["ref"].str.startswith("PMID:")]
               .assign(pmid=lambda d: d["ref"].str.replace("PMID:", "").astype(int))
               .groupby(prim[prim["ref"].str.startswith("PMID:")]
                        ["method.sequencing"].fillna("(missing)"))["pmid"]
               .median())
    print("  median PMID by sequencing method (higher = more recent):")
    for k, v in seq_era.sort_values().items():
        print(f"    {str(k):<16}{int(v)}")

    lines += ["### 3c. Is it the era rather than the method?", "",
              "`sanger` versus `amplicon-seq` is also a proxy for when the work was",
              "done. PMIDs are close enough to monotonic in time to serve as a",
              "recency ordinal.", "",
              f"- {len(with_pmid)} (study, epitope) cells carry a PMID",
              f"- Spearman(PMID as recency, excess z) = **{r_era:+.3f}**, "
              f"permutation p = **{p_era:.4f}**", "",
              "Median PMID by sequencing method:", "",
              "| method | median PMID |", "|---|---:|"]
    for k, v in seq_era.sort_values().items():
        lines.append(f"| {k} | {int(v)} |")
    lines.append("")

    lines += ["## 3. Which method attributes explain the excess?", "",
              "Each level is compared against an epitope-matched expectation built",
              "from the complement, so the epitope mix is held fixed. `p` is a",
              "within-epitope permutation over 2,000 draws.", "",
              "| attribute | level | n | validated | expected | excess | p | epitopes |",
              "|---|---|---:|---:|---:|---:|---:|---:|"]
    for r in attr_rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]:.3f} | {r[4]:.3f} "
                     f"| {r[5]:+.3f} | {r[6]:.3f} | {r[7]} |")
    lines.append("")

    REPORT.write_text("\n".join(lines) + "\n")
    print(f"\nwrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
