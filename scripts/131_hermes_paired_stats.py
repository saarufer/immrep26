#!/usr/bin/env python
"""E152 part 2 -- paired statistics on the acceptance panels.

A collaborator's reading of E152, which is correct: the two dLL results were
reported as "significant correlation", which is the wrong pass condition. What
decides whether the subtraction is worth anything is the **paired difference**
against the scoring it would replace, and against the sequence baseline it has
to beat. With n = 14 and n = 16 the question is also whether one or two
peptides are carrying it.

So, for each system and each pair of scorings, on exactly the same peptides:

  * delta rho, the paired difference in Spearman,
  * a bootstrap interval over peptides,
  * the leave-one-peptide-out range, which is the direct check for whether a
    single peptide drives the result.

No GPU and no inference: reads the per-peptide scores that scripts/130 wrote.

Run: .venv/bin/python scripts/131_hermes_paired_stats.py
"""

from __future__ import annotations

import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[1]
SCORES = ROOT / "data/interim/hermes_acceptance_scores.csv"
OUT = ROOT / "reports/110_hermes_paired_stats.md"
TARGET = "-log10(Kd)"
B = 20000

FIXED = "HERMES-fixed (mean logits)"
DLL = "dLL = full - TCR-removed"
BLO = "BLOSUM62"
PAIRS = [(DLL, FIXED, "does the subtraction help?"),
         (DLL, BLO, "does it beat the sequence baseline?"),
         (FIXED, BLO, "does plain HERMES beat the sequence baseline?")]


def rho(a, y):
    return float(spearmanr(a, y).statistic)


def main() -> int:
    if not SCORES.exists():
        print(f"{SCORES.relative_to(ROOT)} not found; run scripts/130 first.")
        return 1
    S = pd.read_csv(SCORES)
    rng = np.random.default_rng(0)
    rows = []

    for system, df in S.groupby("system", sort=False):
        y = df[TARGET].to_numpy()
        n = len(df)
        print(f"=== {system}, n = {n} ===")
        print(f"  {'scoring':<30}{'rho':>7}")
        for c in (FIXED, DLL, BLO):
            print(f"  {c:<30}{rho(df[c].to_numpy(), y):+7.3f}")

        print(f"\n  {'paired comparison':<34}{'drho':>7}{'95% bootstrap':>18}"
              f"{'leave-one-out range':>22}{'> 0':>7}")
        for a, b, _q in PAIRS:
            xa, xb = df[a].to_numpy(), df[b].to_numpy()
            obs = rho(xa, y) - rho(xb, y)

            boot = np.empty(B)
            for i in range(B):
                k = rng.integers(0, n, n)
                if len(set(y[k])) < 3:
                    boot[i] = np.nan
                    continue
                boot[i] = rho(xa[k], y[k]) - rho(xb[k], y[k])
            boot = boot[np.isfinite(boot)]
            lo, hi = np.percentile(boot, [2.5, 97.5])
            frac = float((boot > 0).mean())

            jack = []
            for i in range(n):
                m = np.ones(n, bool)
                m[i] = False
                jack.append(rho(xa[m], y[m]) - rho(xb[m], y[m]))
            jack = np.array(jack)
            worst = df["name"].to_numpy()[int(np.argmin(jack))]

            print(f"  {a.split(' =')[0] + ' - ' + b:<34}{obs:+7.3f}"
                  f"{f'[{lo:+.2f}, {hi:+.2f}]':>18}"
                  f"{f'[{jack.min():+.2f}, {jack.max():+.2f}]':>22}{frac:7.2f}")
            rows.append([system, a, b, obs, lo, hi, frac,
                         float(jack.min()), float(jack.max()), worst])
        print()

    lines = ["# E152 part 2 — paired statistics on the acceptance panels", "",
             "Generated by `scripts/131_hermes_paired_stats.py`.", "",
             "Pass condition is the **paired** difference, not a significant",
             f"correlation. Bootstrap over peptides, B = {B:,}; the leave-one-out",
             "range is the full span of Δρ when each peptide is dropped in turn.", "",
             "| system | A | B | Δρ | 95% bootstrap | leave-one-out range | P(Δρ>0) | most influential |",
             "|---|---|---|---:|---:|---:|---:|---|"]
    for s, a, b, o, lo, hi, f, jlo, jhi, w in rows:
        lines.append(f"| {s} | {a.split(' =')[0]} | {b} | **{o:+.3f}** | "
                     f"[{lo:+.2f}, {hi:+.2f}] | [{jlo:+.2f}, {jhi:+.2f}] | "
                     f"{f:.2f} | {w} |")
    lines += ["", "Read these as the scale of the question, not as decisions: with 14",
              "and 16 peptides no paired difference of this size is resolvable, which",
              "is itself the finding. The panel in step 2 has to be larger.", ""]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
