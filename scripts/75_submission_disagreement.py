#!/usr/bin/env python
"""Where do the three submissions disagree, and does the disagreement have a shape?

Three entries now exist -- the frozen entry (public 0.8498), D (0.8600) and F
(0.8557). Only one can be the final-scoring submission for a given team, and
every projection that separates them (E47, E74) rests on the published tcrdist3
bands rather than on anything measured on the private rows. So it is worth
asking a question that does not need the private labels at all: *what exactly
are they disagreeing about?*

The method is a pairwise concordance decomposition, which is the natural one
because ROC AUC **is** a pairwise statistic. Within an epitope, enumerate every
(positive, negative) pair. Each submission either orders that pair correctly or
not, so every pair falls into one of four cells:

    both right     neither right     only A right     only B right

The first two cells cancel. The macro AUC difference between two submissions is
therefore *exactly* the per-epitope mean of (only-A − only-B) over all pairs, and
the pairs in those two cells are the entire difference between the entries. They
can then be described: which epitope, which family status, how close the call
was. Purely descriptive -- nothing here is fitted, selected or tuned, and no
submission file is modified.

The decision-relevant version of the question is the pool. D's advantage over
the frozen entry comes partly from a pool-expanded density term, and E27 priced
the public-to-private transfer of pool gain at +0.0112 -> +0.0013. If D's
winning pairs are concentrated on TCRs that actually acquired pool neighbours,
its public margin is the part least likely to survive; if they are not, the
transfer objection does not apply to the margin.

Run: .venv/bin/python scripts/75_submission_disagreement.py
"""

from __future__ import annotations

import importlib.util
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from immrep.data import build_training_frame, load_test  # noqa: E402

REPORT = ROOT / "reports/36_submission_disagreement.md"
FAMILY_RADIUS = 0.12          # E22's single-linkage radius, not nn3_dist
TOPK = 8
ENTRIES = {
    "frozen": "submissions/density3_struct03.csv",
    "D": "submissions/d_density3_m30pool_m50_struct.csv",
    "F": "submissions/f_density3_m30_m50_struct_nopool.csv",
}


def load_module(name: str, path: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def pair_cells(a: np.ndarray, b: np.ndarray, y: np.ndarray):
    """Per (pos, neg) pair: did a order it right, did b. Ties count as 0.5."""
    pos, neg = np.where(y == 1)[0], np.where(y == 0)[0]
    ca = (a[pos][:, None] > a[neg][None, :]).astype(float) \
        + 0.5 * (a[pos][:, None] == a[neg][None, :])
    cb = (b[pos][:, None] > b[neg][None, :]).astype(float) \
        + 0.5 * (b[pos][:, None] == b[neg][None, :])
    return pos, neg, ca, cb


def main() -> int:
    test = load_test()
    labels = build_training_frame()[["tcr_id", "epitope_aa", "pos"]]
    scored = labels.dropna(subset=["pos"]).copy()
    scored["pos"] = scored["pos"].astype(int)

    preds = {}
    for name, path in ENTRIES.items():
        s = pd.read_csv(ROOT / path).set_index("tcr_id")["prediction"]
        preds[name] = s
    merged = scored.set_index("tcr_id")
    for name in ENTRIES:
        merged[name] = preds[name].reindex(merged.index)
    assert merged[list(ENTRIES)].notna().all().all(), "a submission is missing rows"

    lines = ["# E84 -- Pairwise disagreement between the three submissions", "",
             "Descriptive only. No parameter is fitted and no submission file is",
             "touched. Generated by `scripts/75_submission_disagreement.py`.", ""]

    # ---------- 0. the family status of every scorable TCR ----------
    print("building families at SCEPTR cosine <= 0.12 ...")
    sing = load_module("sing", "scripts/49_singleton_classifier.py")
    singleton, _, _, _ = sing.singleton_mask_and_neighbours(test)
    singleton = pd.Series(singleton)
    merged["singleton"] = singleton.reindex(merged.index)

    # ---------- 1. headline per-epitope AUC, to confirm the arithmetic ----------
    hyp = load_module("hyp", "scripts/40_new_hypotheses.py")
    print("\n=== per-epitope AUC, the three entries ===")
    per_ep = {n: hyp.per_epitope(labels, preds[n]) for n in ENTRIES}
    eps = sorted(per_ep["D"])
    hdr = f"  {'epitope':<11}" + "".join(f"{n:>9}" for n in ENTRIES)
    print(hdr)
    rows = []
    for e in eps:
        print(f"  {e:<11}" + "".join(f"{per_ep[n][e]:9.4f}" for n in ENTRIES))
        rows.append([e] + [per_ep[n][e] for n in ENTRIES])
    macro = {n: float(np.mean(list(per_ep[n].values()))) for n in ENTRIES}
    print(f"  {'MACRO':<11}" + "".join(f"{macro[n]:9.4f}" for n in ENTRIES))

    lines += ["## 1. Per-epitope AUC", "",
              "| epitope | " + " | ".join(ENTRIES) + " |",
              "|---|" + "---:|" * len(ENTRIES)]
    for r in rows:
        lines.append(f"| {r[0]} | " + " | ".join(f"{v:.4f}" for v in r[1:]) + " |")
    lines.append("| **MACRO** | "
                 + " | ".join(f"**{macro[n]:.4f}**" for n in ENTRIES) + " |")
    lines.append("")

    # ---------- 2. the pairwise decomposition for each pair of entries ----------
    pairs_to_compare = [("D", "frozen"), ("D", "F"), ("F", "frozen")]
    decomp_tables = {}
    discordant_store = {}
    for a, b in pairs_to_compare:
        print(f"\n=== {a} vs {b}: pairwise concordance decomposition ===")
        print(f"  {'epitope':<11}{'pairs':>8}{'both':>8}{'neither':>9}"
              f"{f'only {a}':>10}{f'only {b}':>10}{'ΔAUC':>9}")
        tbl, total_delta, store = [], [], []
        for e in eps:
            sub = merged[merged["epitope_aa"] == e]
            y = sub["pos"].to_numpy()
            pos, neg, ca, cb = pair_cells(sub[a].to_numpy(), sub[b].to_numpy(), y)
            n = ca.size
            only_a = float(((ca > cb)).sum()) / n
            only_b = float(((cb > ca)).sum()) / n
            both = float(((ca == 1) & (cb == 1)).sum()) / n
            neither = float(((ca == 0) & (cb == 0)).sum()) / n
            delta = ca.mean() - cb.mean()
            total_delta.append(delta)
            tbl.append([e, n, both, neither, only_a, only_b, delta])
            print(f"  {e:<11}{n:8d}{both:8.3f}{neither:9.3f}"
                  f"{only_a:10.3f}{only_b:10.3f}{delta:+9.4f}")
            # keep the discordant pairs themselves, with their identities
            ia, ib = np.where(ca != cb)
            for k in range(len(ia)):
                p, q = pos[ia[k]], neg[ib[k]]
                store.append({
                    "epitope": e,
                    "pos_id": sub.index[p], "neg_id": sub.index[q],
                    "winner": a if ca[ia[k], ib[k]] > cb[ia[k], ib[k]] else b,
                    "gap_a": abs(sub[a].iloc[p] - sub[a].iloc[q]),
                    "gap_b": abs(sub[b].iloc[p] - sub[b].iloc[q]),
                    "pos_singleton": bool(sub["singleton"].iloc[p]),
                    "neg_singleton": bool(sub["singleton"].iloc[q])})
        md = float(np.mean(total_delta))
        print(f"  {'MACRO Δ':<11}{'':8}{'':8}{'':9}{'':10}{'':10}{md:+9.4f}"
              f"   (check: {macro[a] - macro[b]:+.4f})")
        assert abs(md - (macro[a] - macro[b])) < 1e-9
        decomp_tables[(a, b)] = tbl
        discordant_store[(a, b)] = pd.DataFrame(store)

    lines += ["## 2. The pairwise concordance decomposition", "",
              "Within each epitope every (positive, negative) pair is placed in one",
              "of four cells. `both` and `neither` cancel; the macro AUC difference",
              "is exactly the mean of (only-A − only-B), which is asserted in code.",
              ""]
    for (a, b), tbl in decomp_tables.items():
        lines += [f"### {a} vs {b}", "",
                  f"| epitope | pairs | both | neither | only {a} | only {b} | ΔAUC |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for r in tbl:
            lines.append(f"| {r[0]} | {r[1]} | {r[2]:.3f} | {r[3]:.3f} | "
                         f"{r[4]:.3f} | {r[5]:.3f} | {r[6]:+.4f} |")
        lines.append(f"| **MACRO** | | | | | | **{macro[a] - macro[b]:+.4f}** |")
        lines.append("")

    # ---------- 3. what the discordant pairs look like ----------
    print("\n=== the shape of the disagreement (D vs frozen) ===")
    d = discordant_store[("D", "frozen")]
    print(f"  discordant pairs: {len(d)}  "
          f"({(d['winner'] == 'D').mean():.1%} won by D)")
    print("\n  by epitope:")
    for e, g in d.groupby("epitope"):
        print(f"    {e:<11} {len(g):6d} pairs   D wins {(g['winner']=='D').mean():.1%}")
    print("\n  by family status of the pair's two members:")
    d["cls"] = np.where(d["pos_singleton"] & d["neg_singleton"], "both singleton",
                np.where(~d["pos_singleton"] & ~d["neg_singleton"], "both clustered",
                         "mixed"))
    for c, g in d.groupby("cls"):
        print(f"    {c:<16} {len(g):6d} pairs   D wins {(g['winner']=='D').mean():.1%}")
    print("\n  how close the call is (median |score gap| of the winner):")
    for w, g in d.groupby("winner"):
        col = "gap_a" if w == "D" else "gap_b"
        print(f"    {w:<8} median winning gap {g[col].median():.4f}   "
              f"median losing gap {g['gap_b' if w=='D' else 'gap_a'].median():.4f}")

    lines += ["## 3. The shape of the D-vs-frozen disagreement", "",
              f"{len(d)} discordant pairs, **{(d['winner']=='D').mean():.1%} won by D**.",
              "", "| split | pairs | D wins |", "|---|---:|---:|"]
    for e, g in d.groupby("epitope"):
        lines.append(f"| {e} | {len(g)} | {(g['winner']=='D').mean():.1%} |")
    for c, g in d.groupby("cls"):
        lines.append(f"| {c} | {len(g)} | {(g['winner']=='D').mean():.1%} |")
    lines.append("")

    # ---------- 4. is D's margin on the pool? ----------
    print("\n=== is D's winning margin concentrated on pool-affected TCRs? ===")
    print("  rebuilding the same-epitope pool and counting, per TCR, how many of")
    print("  its top-8 density neighbours are pool rows rather than cohort rows.")
    pool_mod = load_module("pool", "scripts/33_pool_negative_control.py")
    pool = pool_mod.load_pool()
    pool_frac = pd.Series(index=test["tcr_id"], dtype=float)
    pool_counts = {}
    for epitope, cohort in test.groupby("epitope_aa"):
        cohort = cohort.reset_index(drop=True)
        frame = pd.DataFrame({
            "cdr3a": cohort["cdr3_alpha_aa"], "cdr3b": cohort["cdr3_beta_aa"],
            "trav": cohort["TRAV_IMGT"], "traj": cohort["TRAJ_IMGT"],
            "trbv": cohort["TRBV_IMGT"], "trbj": cohort["TRBJ_IMGT"],
            "ep": epitope})
        vectors = pool_mod.embed(frame)
        keys = set(zip(cohort["cdr3_alpha_aa"], cohort["cdr3_beta_aa"]))
        same = pool[pool["ep"] == epitope]
        extra = same[[(a, b) not in keys for a, b in
                      zip(same["cdr3a"], same["cdr3b"])]].drop_duplicates(
                          ["cdr3a", "cdr3b"])
        pool_counts[epitope] = len(extra)
        if extra.empty:
            pool_frac.loc[cohort["tcr_id"]] = 0.0
            print(f"  {epitope:<11} no pool rows available")
            continue
        reference = np.vstack([vectors, pool_mod.embed(extra)])
        dist = 1.0 - vectors @ reference.T
        dist[np.arange(len(cohort)), np.arange(len(cohort))] = np.inf
        order = np.argsort(dist, axis=1)[:, :TOPK]
        is_pool = (order >= len(cohort)).mean(axis=1)
        pool_frac.loc[cohort["tcr_id"]] = is_pool
        print(f"  {epitope:<11} pool rows {len(extra):5d}   mean pool share "
              f"of top-8 {is_pool.mean():.3f}")

    d["pos_pool"] = pool_frac.reindex(d["pos_id"]).to_numpy()
    d["neg_pool"] = pool_frac.reindex(d["neg_id"]).to_numpy()
    d["pair_pool"] = np.maximum(d["pos_pool"], d["neg_pool"])
    print("\n  discordant pairs split by whether either member is pool-affected:")
    print(f"  {'pool share of top-8':<24}{'pairs':>8}{'D wins':>9}{'net to D':>10}")
    bins = [(-0.01, 0.0, "neither member (0)"), (0.0, 0.25, "0 < max <= 0.25"),
            (0.25, 0.5, "0.25 < max <= 0.5"), (0.5, 1.01, "max > 0.5")]
    pool_rows = []
    for lo, hi, lab in bins:
        g = d[(d["pair_pool"] > lo) & (d["pair_pool"] <= hi)]
        if g.empty:
            continue
        win = (g["winner"] == "D").mean()
        net = (2 * win - 1) * len(g)
        print(f"  {lab:<24}{len(g):8d}{win:9.1%}{net:+10.0f}")
        pool_rows.append([lab, len(g), win, net])
    pool_free = d[d["pair_pool"] == 0]
    print(f"\n  pool-free share of all discordant pairs: "
          f"{len(pool_free)/len(d):.1%}")
    print(f"  net pairs to D among pool-free:    "
          f"{(2*(pool_free['winner']=='D').mean()-1)*len(pool_free):+.0f}")
    print(f"  net pairs to D among pool-affected:"
          f"{(2*(d[d['pair_pool']>0]['winner']=='D').mean()-1)*len(d[d['pair_pool']>0]):+.0f}")

    # ---------- 4b. the same split with the epitope held fixed ----------
    # The split above is confounded: pool-affected TCRs sit in the large
    # cohorts (GIL, NLV) and those are also where D wins for other reasons.
    # Stratifying inside each epitope removes that confound.
    print("\n=== the same split, epitope held fixed ===")
    print(f"  {'epitope':<11}{'pool-free pairs':>16}{'D wins':>9}"
          f"{'pooled pairs':>14}{'D wins':>9}")
    strat_rows = []
    for e, g in d.groupby("epitope"):
        free, used = g[g["pair_pool"] == 0], g[g["pair_pool"] > 0]
        wf = (free["winner"] == "D").mean() if len(free) else float("nan")
        wu = (used["winner"] == "D").mean() if len(used) else float("nan")
        print(f"  {e:<11}{len(free):16d}{wf:9.1%}{len(used):14d}{wu:9.1%}")
        strat_rows.append([e, len(free), wf, len(used), wu])

    # ---------- 4c. the decomposition that is not confounded ----------
    # F is D with the pool removed everywhere, so (F - frozen) is pool-free
    # *by construction* and (D - F) is the pool's own contribution. That is a
    # control, not a correlation.
    print("\n=== D - frozen split by construction rather than by correlation ===")
    df_frozen = macro["D"] - macro["frozen"]
    f_frozen = macro["F"] - macro["frozen"]
    d_f = macro["D"] - macro["F"]
    print(f"  F - frozen  (pool-free by construction)  {f_frozen:+.4f}"
          f"   {f_frozen/df_frozen:.0%} of D's margin")
    print(f"  D - F       (the pool's contribution)    {d_f:+.4f}"
          f"   {d_f/df_frozen:.0%} of D's margin")
    print("\n  and the pool's contribution against how much pool each epitope has:")
    print(f"  {'epitope':<11}{'pool rows':>11}{'top-8 share':>13}{'D - F':>9}")
    dose = []
    for e in eps:
        share = float(pool_frac.reindex(
            test[test['epitope_aa'] == e]['tcr_id']).mean())
        gain = per_ep["D"][e] - per_ep["F"][e]
        n_pool = int(pool_counts[e])
        print(f"  {e:<11}{n_pool:11d}{share:13.3f}{gain:+9.4f}")
        dose.append([e, n_pool, share, gain])
    from scipy.stats import spearmanr
    rho = spearmanr([r[2] for r in dose], [r[3] for r in dose]).statistic
    print(f"\n  Spearman(top-8 pool share, D - F) over the five public epitopes:"
          f" {rho:+.3f}")
    print("  the three private epitopes' own pool availability:")
    for e in ("CINGVCWTV", "LLWNGPMAV", "LTDEMIAQY"):
        share = float(pool_frac.reindex(
            test[test['epitope_aa'] == e]['tcr_id']).mean())
        print(f"    {e:<11}{int(pool_counts[e]):11d}{share:13.3f}")

    lines += ["## 4. Is D's margin on the pool?", "",
              "Per TCR, the share of its top-8 density neighbours that are pool rows",
              "rather than cohort rows; each discordant pair takes the larger of its",
              "two members' shares.", "",
              "| pool share of top-8 | pairs | D wins | net pairs to D |",
              "|---|---:|---:|---:|"]
    for r in pool_rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]:.1%} | {r[3]:+.0f} |")
    lines += ["",
              f"Pool-free share of all discordant pairs: "
              f"**{len(pool_free)/len(d):.1%}**.", "",
              "### 4b. The same split with the epitope held fixed", "",
              "The split above is confounded -- pool-affected TCRs sit in the large",
              "cohorts, and those are also where D wins for other reasons.", "",
              "| epitope | pool-free pairs | D wins | pooled pairs | D wins |",
              "|---|---:|---:|---:|---:|"]
    for r in strat_rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]:.1%} | {r[3]} | {r[4]:.1%} |")
    lines += ["", "### 4c. The decomposition that is a control, not a correlation", "",
              "F is D with the pool removed everywhere, so `F - frozen` is pool-free",
              "*by construction* and `D - F` is the pool's own contribution.", "",
              f"- `F - frozen` = **{f_frozen:+.4f}** ({f_frozen/df_frozen:.0%} of D's margin), pool-free by construction",
              f"- `D - F` = **{d_f:+.4f}** ({d_f/df_frozen:.0%} of D's margin), the pool",
              "",
              "| epitope | pool rows | top-8 pool share | D − F |",
              "|---|---:|---:|---:|"]
    for r in dose:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]:.3f} | {r[3]:+.4f} |")
    lines += ["",
              f"Spearman(top-8 pool share, D − F) over the five public epitopes: "
              f"**{rho:+.3f}**.", ""]

    REPORT.write_text("\n".join(lines) + "\n")
    print(f"\nwrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
