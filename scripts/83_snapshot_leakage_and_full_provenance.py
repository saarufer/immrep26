#!/usr/bin/env python
"""E90 re-run against a pre-revalidation VDJdb snapshot, with the fields it skipped.

A collaborator raised three objections to E90, and the first is substantive.

**1. Snapshot leakage.** E90 used `vdjdb-2026-06-03`, the current rolling
release. The IMMREP26 labels come from a revalidation published in 2026, so any
record VDJdb absorbed *after* that work -- including, potentially, the
revalidation's own results -- is not part of the historical provenance being
analysed. The 2026 release holds **192,754** rows against **62,178** in
`2023-06-01`, a 3.1x growth, so this is not a hypothetical. The nearest release
to the suggested May-2023 cut is **2023-06-01**; there is no May 2023 release.
Everything below is computed on both snapshots side by side, and the question
is whether any conclusion moves.

**2. One receptor, several studies.** E90's primary analysis kept only the
1,615 TCRs with exactly one reference, which is clean for attribution but
discards the multi-source evidence rather than using it. Here every
(TCR, reference) pair contributes, with each TCR's weight split across its
references so a widely-reported clonotype does not count several times.

**3. Fields E90 skipped.** `method.verification` -- did the original study
independently verify this TCR -- and `method.frequency` -- how common was it
among the selected cells -- were both left out. The first is the most directly
relevant field in the whole schema and is added here.

**What remains out of reach, and should be said rather than glossed.** Whether
a given public family entered the literature through motif-guided enrichment,
V-gene preselection or a clone-size threshold is a property of the original
paper's methods section. No VDJdb field records it. This script reports which
families would need that manual check, but cannot perform it.

Run: .venv/bin/python scripts/83_snapshot_leakage_and_full_provenance.py
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from immrep.data import build_training_frame, load_test  # noqa: E402

REPORT = ROOT / "reports/58_snapshot_leakage_provenance.md"
SNAPSHOTS = {
    "2023-06-01 (pre-revalidation)":
        ROOT / "data/external/vdjdb/vdjdb-2023-06-01/vdjdb_full.txt",
    "2026-06-03 (used by E90)":
        ROOT / "data/external/vdjdb/vdjdb-2026-06-03/vdjdb_full.txt",
}
MIN_N = 10
SEED = 0


def load_snapshot(path: Path, keys: set) -> pd.DataFrame:
    f = pd.read_csv(path, sep="\t", low_memory=False)
    f = f[(f["species"] == "HomoSapiens")
          & f["cdr3.alpha"].notna() & f["cdr3.beta"].notna()].copy()
    f["_k"] = f["cdr3.alpha"] + "|" + f["cdr3.beta"] + "|" + f["antigen.epitope"]
    return f[f["_k"].isin(keys)].copy()


def main() -> int:
    test = load_test().copy()
    labels = build_training_frame()[["tcr_id", "epitope_aa", "pos"]]
    test["_k"] = (test["cdr3_alpha_aa"] + "|" + test["cdr3_beta_aa"] + "|"
                  + test["epitope_aa"])
    scored = labels.dropna(subset=["pos"]).copy()
    scored["pos"] = scored["pos"].astype(int)
    pub = scored.merge(test[["tcr_id", "_k", "split"]], on="tcr_id")
    key_pos = pub.groupby("_k")["pos"].mean()
    key_ep = pub.drop_duplicates("_k").set_index("_k")["epitope_aa"]
    allkeys = set(test["_k"])

    snaps = {name: load_snapshot(p, allkeys) for name, p in SNAPSHOTS.items()}

    lines = ["# E92 — E90 against a pre-revalidation snapshot, with the missing fields",
             "", "Generated by",
             "`scripts/83_snapshot_leakage_and_full_provenance.py`.", ""]

    # ---------- 1. how much did the database change? ----------
    print("=== 1. coverage, by snapshot ===")
    print(f"  {'snapshot':<32}{'records':>9}{'keys':>8}{'refs':>7}"
          f"{'ref null':>10}{'subj':>7}{'verif':>8}")
    cov_rows = []
    for name, h in snaps.items():
        r = [name, len(h), h["_k"].nunique(), h["reference.id"].nunique(),
             float(h["reference.id"].isna().mean()),
             float(h["meta.subject.id"].notna().mean()),
             float(h["method.verification"].notna().mean())]
        print(f"  {name:<32}{r[1]:9d}{r[2]:8d}{r[3]:7d}{r[4]:10.1%}"
              f"{r[5]:7.1%}{r[6]:8.1%}")
        cov_rows.append(r)

    print("\n  per epitope, keys matched in each snapshot:")
    print(f"  {'epitope':<12}{'split':<9}{'rows':>6}"
          + "".join(f"{n.split()[0]:>14}" for n in snaps))
    ep_rows = []
    for e, g in test.groupby("epitope_aa"):
        ks = set(g["_k"])
        row = [e, g["split"].mode().iloc[0], len(g)] + [
            len(ks & set(h["_k"])) for h in snaps.values()]
        print(f"  {row[0]:<12}{row[1]:<9}{row[2]:6d}"
              + "".join(f"{v:14d}" for v in row[3:]))
        ep_rows.append(row)

    old, new = list(snaps.values())
    added = set(new["_k"]) - set(old["_k"])
    print(f"\n  keys present in 2026 but ABSENT from 2023: {len(added)} "
          f"({len(added)/len(allkeys):.1%} of the competition set)")
    new_refs = set(new["reference.id"].dropna()) - set(old["reference.id"].dropna())
    print(f"  references present in 2026 but not 2023: {len(new_refs)}")
    for r in sorted(new_refs)[:12]:
        n = int((new["reference.id"] == r).sum())
        print(f"    {str(r)[:62]:<64}{n:5d} records")

    lines += ["## 1. How much did the database change?", "",
              "| snapshot | records | keys | refs | ref.id null | subject | verification |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for r in cov_rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]:.1%} "
                     f"| {r[5]:.1%} | {r[6]:.1%} |")
    lines += ["", "Keys matched per epitope:", "",
              "| epitope | split | rows | " + " | ".join(
                  n.split()[0] for n in snaps) + " |",
              "|---|---|---:|---:|---:|"]
    for r in ep_rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} |")
    lines += ["",
              f"- competition keys present in 2026 but **absent from 2023**: "
              f"**{len(added)}** ({len(added)/len(allkeys):.1%})",
              f"- references present in 2026 but not 2023: **{len(new_refs)}**", ""]

    # ---------- 2. the per-study table on both snapshots ----------
    def study_table(h: pd.DataFrame) -> pd.DataFrame:
        """Every (TCR, reference) pair contributes, weighted 1/n_refs."""
        j = h[["_k", "reference.id"]].dropna().drop_duplicates()
        j = j[j["_k"].isin(key_pos.index)]
        w = 1.0 / j.groupby("_k")["reference.id"].transform("size")
        j = j.assign(w=w, pos=j["_k"].map(key_pos),
                     epitope=j["_k"].map(key_ep))
        cells = (j.groupby(["reference.id", "epitope"])
                 .apply(lambda d: pd.Series({
                     "n_eff": d["w"].sum(), "n_raw": len(d),
                     "rate": np.average(d["pos"], weights=d["w"])}))
                 .reset_index())
        cells = cells[cells["n_eff"] >= MIN_N].copy()
        exp = []
        for _, r in cells.iterrows():
            rest = j[(j["epitope"] == r["epitope"])
                     & (j["reference.id"] != r["reference.id"])]
            exp.append(np.average(rest["pos"], weights=rest["w"])
                       if len(rest) else np.nan)
        cells["expected"] = exp
        cells["excess"] = cells["rate"] - cells["expected"]
        cells["z"] = ((cells["rate"] - cells["expected"])
                      * np.sqrt(cells["n_eff"])
                      / np.sqrt(cells["expected"] * (1 - cells["expected"])))
        return cells.sort_values("z")

    print("\n=== 2. the per-study table, both snapshots, multi-reference kept ===")
    tabs = {}
    for name, h in snaps.items():
        t = study_table(h)
        tabs[name] = t
        print(f"\n  --- {name}: {len(t)} cells, "
              f"{t['reference.id'].nunique()} studies, "
              f"{t['n_eff'].sum():.0f} effective TCRs ---")
        print(f"  {'study':<34}{'epitope':<12}{'n_eff':>7}{'rate':>8}"
              f"{'exp':>8}{'excess':>9}{'z':>7}")
        for _, r in t.iterrows():
            print(f"  {str(r['reference.id'])[:33]:<34}{r['epitope'][:11]:<12}"
                  f"{r['n_eff']:7.1f}{r['rate']:8.3f}{r['expected']:8.3f}"
                  f"{r['excess']:+9.3f}{r['z']:+7.2f}")

    # do the two snapshots agree on which studies are bad?
    a, b = tabs.values()
    merged = a.merge(b, on=["reference.id", "epitope"], suffixes=("_23", "_26"))
    rho = stats.spearmanr(merged["excess_23"], merged["excess_26"]).statistic
    print(f"\n  cells present in both snapshots: {len(merged)}")
    print(f"  Spearman(excess 2023, excess 2026) = {rho:+.3f}")
    print(f"  max |difference| in excess: "
          f"{(merged['excess_23'] - merged['excess_26']).abs().max():.3f}")

    lines += ["## 2. The per-study table on both snapshots", "",
              "Every (TCR, reference) pair contributes, each TCR weighted `1/n_refs`",
              "so a widely-reported clonotype does not count several times — E90",
              "instead discarded the 162 multi-reference TCRs.", ""]
    for name, t in tabs.items():
        lines += [f"### {name}", "",
                  f"{len(t)} cells, {t['reference.id'].nunique()} studies, "
                  f"{t['n_eff'].sum():.0f} effective TCRs", "",
                  "| study | epitope | n_eff | rate | expected | excess | z |",
                  "|---|---|---:|---:|---:|---:|---:|"]
        for _, r in t.iterrows():
            lines.append(f"| {r['reference.id']} | {r['epitope']} "
                         f"| {r['n_eff']:.1f} | {r['rate']:.3f} "
                         f"| {r['expected']:.3f} | {r['excess']:+.3f} "
                         f"| {r['z']:+.2f} |")
        lines.append("")
    lines += [f"Cells present in both: **{len(merged)}**. "
              f"Spearman(excess 2023, excess 2026) = **{rho:+.3f}**, "
              f"max |difference| "
              f"{(merged['excess_23'] - merged['excess_26']).abs().max():.3f}.", ""]

    # ---------- 3. the fields E90 skipped ----------
    print("\n=== 3. method.verification and method.frequency, both snapshots ===")
    ver_rows = []
    for name, h in snaps.items():
        one = h.drop_duplicates("_k").set_index("_k")
        v = one["method.verification"].reindex(key_pos.index)
        pop = v.notna() & (v.astype(str).str.strip() != "")
        print(f"\n  --- {name} --- verification populated on "
              f"{pop.sum()} of {len(v)} scorable keys")
        if pop.sum() >= 25:
            df = pd.DataFrame({"v": v.where(pop, "(missing)").astype(str),
                               "pos": key_pos.reindex(v.index),
                               "ep": key_ep.reindex(v.index)})
            for lvl, g in df.groupby("v"):
                if len(g) < 15:
                    continue
                comp = df[df["v"] != lvl]
                eps = [e for e in g["ep"].unique() if (comp["ep"] == e).any()]
                if not eps:
                    continue
                gg = g[g["ep"].isin(eps)]
                w = gg["ep"].value_counts(normalize=True)
                exp = sum(w[e] * comp[comp["ep"] == e]["pos"].mean() for e in eps)
                nstudy = h[h["_k"].isin(gg.index)]["reference.id"].nunique()
                print(f"    {lvl[:34]:<36}{len(gg):5d}{gg['pos'].mean():8.3f}"
                      f"{exp:8.3f}{gg['pos'].mean()-exp:+9.3f}   studies {nstudy}")
                ver_rows.append([name, lvl, len(gg), gg["pos"].mean(), exp,
                                 gg["pos"].mean() - exp, nstudy])

    # E91's lesson: count the studies behind each level before believing it.
    print("\n  how many studies stand behind each verification level?")
    collin = []
    for name, h in snaps.items():
        one = h.drop_duplicates("_k").set_index("_k")
        v = one["method.verification"].reindex(key_pos.index)
        for lvl in v.dropna().unique():
            ks = v[v == lvl].index
            if len(ks) < 15:
                continue
            refs = h[h["_k"].isin(ks)]["reference.id"].value_counts()
            top = refs.iloc[0] / refs.sum()
            print(f"    {name[:10]}  {lvl[:28]:<30}n={len(ks):4d}  "
                  f"studies={len(refs):2d}  top={top:.0%} "
                  f"({str(refs.index[0])[:34]})")
            collin.append([name, lvl, len(ks), len(refs), float(top),
                           str(refs.index[0])])

    print("\n  method.frequency (clonal frequency in the original experiment)")
    freq_rows = []
    for name, h in snaps.items():
        one = h.drop_duplicates("_k").set_index("_k")
        raw = one["method.frequency"].reindex(key_pos.index).astype(str)
        # values look like "3/1000" or "0.003"; parse both
        def parse(s):
            s = s.strip()
            if s in ("", "nan", "none", "na"):
                return np.nan
            try:
                if "/" in s:
                    a, b = s.split("/")[:2]
                    return float(a) / float(b) if float(b) else np.nan
                return float(s)
            except Exception:
                return np.nan
        fr = raw.map(parse)
        ok = fr.notna() & np.isfinite(fr)
        print(f"  --- {name} --- parsed on {int(ok.sum())} of {len(fr)} keys")
        if ok.sum() >= 50:
            rhos = []
            for e in sorted(key_ep.unique()):
                sel = ok & (key_ep.reindex(fr.index) == e)
                if sel.sum() >= 25 and fr[sel].nunique() > 1:
                    r_ = stats.spearmanr(fr[sel], key_pos.reindex(fr.index)[sel]).statistic
                    rhos.append((e, int(sel.sum()), r_))
            for e, n, r_ in rhos:
                print(f"    {e:<12}{n:6d}  within-epitope ρ with validation {r_:+.3f}")
            freq_rows.append([name, rhos])

    lines += ["## 3. The fields E90 skipped", "",
              "### `method.verification` — did the original study verify the TCR?", "",
              "| snapshot | level | n | validated | expected | excess | studies |",
              "|---|---|---:|---:|---:|---:|---:|"]
    for r in ver_rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]:.3f} | {r[4]:.3f} "
                     f"| {r[5]:+.3f} | {r[6]} |")
    lines += ["",
              "How many studies stand behind each level (E91's lesson):", "",
              "| snapshot | level | n | studies | largest share | that study |",
              "|---|---|---:|---:|---:|---|"]
    for r in collin:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | **{r[4]:.0%}** "
                     f"| {r[5]} |")
    lines += ["", "### `method.frequency` — clonal frequency in the source experiment",
              "", "| snapshot | epitope | n | within-epitope ρ with validation |",
              "|---|---|---:|---:|"]
    for name, rhos in freq_rows:
        for e, n, r_ in rhos:
            lines.append(f"| {name} | {e} | {n} | {r_:+.3f} |")
    lines.append("")

    REPORT.write_text("\n".join(lines) + "\n")
    print(f"\nwrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
