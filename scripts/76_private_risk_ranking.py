#!/usr/bin/env python
"""Inverting the difficulty model: on which private epitope is a configuration
most likely to fail?

E74 fitted a margin model -- our gain over tcrdist3 is a roughly constant
fraction of tcrdist3's remaining headroom -- and validated it at leave-one-
epitope-out MAE 0.0156, against 0.0301 for the uniform margin E47 assumed. That
model was used forwards, to produce a private point estimate. It can also be
used backwards, to ask which epitope carries the risk. That raises no score, but
it is the difference between a number and a number with a stated failure mode.

Four risk axes are assembled, each from a quantity that is measurable without
the private labels:

  1. **Band risk.** The published tcrdist3 AUROC and the fitted headroom
     fraction give a predicted per-epitope AUC and an interval from the band's
     own width. LTDEMIAQY's band (0.66-0.68) sits *below* every public epitope,
     so its prediction is an extrapolation, not an interpolation.

  2. **Fraction risk.** The headroom fraction is "constant" only on average --
     it ranges 0.099 to 0.335 over the five public epitopes, a 3.4x spread.
     Re-predicting each private epitope under every observed fraction gives the
     range the model itself cannot resolve.

  3. **Sampling risk.** The AUC of a small cohort is noisy on its own. The
     Hanley-McNeil standard error at each private cohort's size and base rate
     says how much of the uncertainty is irreducible.

  4. **Mechanism risk.** E20 and E72 established how the density mechanism
     fails: GLCTLVAML's cohort is so convergent that density has no dynamic
     range, and the failure is visible label-free in the family structure. The
     same diagnostics run on the private cohorts, so an epitope can be flagged
     as GLC-like *before* seeing any label. This is the only axis that is not
     downstream of the published paper.

Plus the pool axis that E84 measured: the pool contribution D holds over F is
zero where a cohort has few same-epitope pool rows, and two of the three
private epitopes have almost none.

Nothing is fitted to anything private and no submission file is touched.

Run: .venv/bin/python scripts/76_private_risk_ranking.py
"""

from __future__ import annotations

import importlib.util
import sys
import warnings
from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd
import scipy.sparse as sp
from scipy.sparse.csgraph import connected_components

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from immrep.data import build_training_frame, load_test  # noqa: E402

REPORT = ROOT / "reports/51_private_risk_ranking.md"
FAMILY_RADIUS = 0.12

# E47: tcrdist3's published per-epitope AUROC, from the Immunity paper.
PUBLISHED = {"GILGFVFTL": 0.871, "YLQPRTFLL": 0.928, "NLVPMVATV": 0.809,
             "TTDPSFLGRY": 0.826, "GLCTLVAML": 0.690}
PRIVATE_BANDS = {"CINGVCWTV": (0.80, 0.83), "LLWNGPMAV": (0.80, 0.83),
                 "LTDEMIAQY": (0.66, 0.68)}
ENTRIES = {
    "frozen": "submissions/density3_struct03.csv",
    "D": "submissions/d_density3_m30pool_m50_struct.csv",
    "F": "submissions/f_density3_m30_m50_struct_nopool.csv",
}


def load_module(name: str, path: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def hanley_mcneil_se(auc: float, n_pos: int, n_neg: int) -> float:
    """SE of a single AUC estimate, the exponential approximation."""
    if n_pos < 1 or n_neg < 1:
        return float("nan")
    q1 = auc / (2.0 - auc)
    q2 = 2.0 * auc ** 2 / (1.0 + auc)
    var = (auc * (1 - auc) + (n_pos - 1) * (q1 - auc ** 2)
           + (n_neg - 1) * (q2 - auc ** 2)) / (n_pos * n_neg)
    return float(np.sqrt(max(var, 0.0)))


def main() -> int:
    test = load_test()
    labels = build_training_frame()[["tcr_id", "epitope_aa", "pos"]]
    hyp = load_module("hyp", "scripts/40_new_hypotheses.py")

    preds, per_ep = {}, {}
    for name, path in ENTRIES.items():
        preds[name] = pd.read_csv(ROOT / path).set_index("tcr_id")["prediction"]
        per_ep[name] = hyp.per_epitope(labels, preds[name])
    macro = {n: float(np.mean(list(per_ep[n].values()))) for n in ENTRIES}

    lines = ["# E85 -- Inverting the difficulty model into a private risk ranking",
             "",
             "No score follows from this. It converts E74's point estimate into a",
             "per-epitope risk ordering with a stated failure mode, from quantities",
             "measurable without the private labels.",
             "Generated by `scripts/76_private_risk_ranking.py`.", ""]

    # ---------- 1. the fitted headroom fraction, and its spread ----------
    print("=== 1. the headroom fraction, per public epitope and per entry ===")
    print(f"  {'epitope':<11}{'tcrdist3':>9}{'headroom':>10}", end="")
    for n in ENTRIES:
        print(f"{n + ' f':>11}", end="")
    print()
    fractions = {n: {} for n in ENTRIES}
    for e, base in sorted(PUBLISHED.items(), key=lambda kv: kv[1]):
        head = 1.0 - base
        print(f"  {e:<11}{base:9.3f}{head:10.3f}", end="")
        for n in ENTRIES:
            f = (per_ep[n][e] - base) / head
            fractions[n][e] = f
            print(f"{f:11.3f}", end="")
        print()
    print(f"  {'mean f':<11}{'':9}{'':10}", end="")
    for n in ENTRIES:
        print(f"{np.mean(list(fractions[n].values())):11.3f}", end="")
    print()
    print(f"  {'spread':<11}{'':9}{'':10}", end="")
    for n in ENTRIES:
        v = list(fractions[n].values())
        print(f"{max(v) - min(v):11.3f}", end="")
    print()

    lines += ["## 1. The headroom fraction and its spread", "",
              "| epitope | tcrdist3 | headroom | "
              + " | ".join(f"{n} f" for n in ENTRIES) + " |",
              "|---|---:|---:|" + "---:|" * len(ENTRIES)]
    for e, base in sorted(PUBLISHED.items(), key=lambda kv: kv[1]):
        lines.append(f"| {e} | {base:.3f} | {1-base:.3f} | "
                     + " | ".join(f"{fractions[n][e]:.3f}" for n in ENTRIES) + " |")
    lines.append("| **mean** | | | " + " | ".join(
        f"**{np.mean(list(fractions[n].values())):.3f}**" for n in ENTRIES) + " |")
    lines.append("| spread | | | " + " | ".join(
        f"{max(fractions[n].values()) - min(fractions[n].values()):.3f}"
        for n in ENTRIES) + " |")
    lines.append("")

    # ---------- 2. band risk and fraction risk, per private epitope ----------
    print("\n=== 2. predicted private AUC: the band and the fraction separately ===")
    print("  'band' varies tcrdist3 over the published interval at the mean f;")
    print("  'fraction' varies f over the five observed values at the band midpoint.")
    band_tbl = []
    for n in ENTRIES:
        fs = np.array(list(fractions[n].values()))
        print(f"\n  --- {n} (mean f {fs.mean():.3f}) ---")
        print(f"  {'epitope':<11}{'point':>8}{'band lo':>9}{'band hi':>9}"
              f"{'frac lo':>9}{'frac hi':>9}{'total width':>13}")
        for e, (lo, hi) in PRIVATE_BANDS.items():
            mid = (lo + hi) / 2
            point = mid + fs.mean() * (1 - mid)
            b_lo = lo + fs.mean() * (1 - lo)
            b_hi = hi + fs.mean() * (1 - hi)
            f_lo = mid + fs.min() * (1 - mid)
            f_hi = mid + fs.max() * (1 - mid)
            width = max(b_hi, f_hi) - min(b_lo, f_lo)
            print(f"  {e:<11}{point:8.3f}{b_lo:9.3f}{b_hi:9.3f}"
                  f"{f_lo:9.3f}{f_hi:9.3f}{width:13.3f}")
            band_tbl.append([n, e, point, b_lo, b_hi, f_lo, f_hi, width])

    lines += ["## 2. Band risk versus fraction risk", "",
              "`band` varies tcrdist3 across the published interval at the mean",
              "fraction; `fraction` varies the fraction across its five observed",
              "values at the band midpoint. The two are separate failure modes.", "",
              "| entry | epitope | point | band lo | band hi | frac lo | frac hi | width |",
              "|---|---|---:|---:|---:|---:|---:|---:|"]
    for r in band_tbl:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]:.3f} | {r[3]:.3f} | {r[4]:.3f} "
                     f"| {r[5]:.3f} | {r[6]:.3f} | **{r[7]:.3f}** |")
    lines.append("")

    # ---------- 3. sampling risk from the private cohort sizes ----------
    print("\n=== 3. sampling risk: how noisy is each private AUC on its own? ===")
    print("  The private base rate is unknown, so the SE is reported across a")
    print("  range of plausible positive fractions, at the point prediction.")
    priv = test[test["epitope_aa"].isin(PRIVATE_BANDS)]
    print(f"  {'epitope':<11}{'rows':>6}{'SE @20% pos':>13}{'SE @40%':>9}"
          f"{'SE @50%':>9}")
    samp_tbl = []
    fs_d = np.array(list(fractions["D"].values()))
    for e in PRIVATE_BANDS:
        n_rows = int((priv["epitope_aa"] == e).sum())
        mid = sum(PRIVATE_BANDS[e]) / 2
        point = mid + fs_d.mean() * (1 - mid)
        ses = []
        for rate in (0.20, 0.40, 0.50):
            n_pos = int(round(n_rows * rate))
            ses.append(hanley_mcneil_se(point, n_pos, n_rows - n_pos))
        print(f"  {e:<11}{n_rows:6d}{ses[0]:13.4f}{ses[1]:9.4f}{ses[2]:9.4f}")
        samp_tbl.append([e, n_rows] + ses)

    lines += ["## 3. Sampling risk from the private cohort sizes", "",
              "| epitope | rows | SE @20% pos | SE @40% | SE @50% |",
              "|---|---:|---:|---:|---:|"]
    for r in samp_tbl:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]:.4f} | {r[3]:.4f} | {r[4]:.4f} |")
    lines.append("")

    # ---------- 4. mechanism risk: is any private cohort GLC-like? ----------
    print("\n=== 4. mechanism risk: does density have dynamic range there? ===")
    print("  The GLC failure (E20, E72) is visible label-free in the family")
    print("  structure, so the same diagnostics run on the private cohorts.")
    cached = np.load(ROOT / "data/interim/sceptr/default.npz", allow_pickle=True)
    vectors = cached["vectors"]
    vectors = vectors / np.linalg.norm(vectors, axis=1, keepdims=True)
    where = {t: i for i, t in enumerate(cached["tcr_id"])}
    donor_col = "data_origin"
    print(f"  {'epitope':<11}{'rows':>6}{'singl%':>8}{'maxfam':>8}"
          f"{'close%':>8}{'nn3 IQR':>9}{'nn3 sd':>8}  split")
    mech_tbl = []
    for e, cohort in test.groupby("epitope_aa"):
        ids = cohort["tcr_id"].to_numpy()
        block = vectors[[where[t] for t in ids]]
        dm = 1.0 - block @ block.T
        _, fam = connected_components(
            sp.csr_matrix(dm <= FAMILY_RADIUS), directed=False)
        sizes = pd.Series(fam).value_counts()
        singl = float((sizes[fam] == 1).mean())
        maxfam = int(sizes.max())
        iu = np.triu_indices(len(ids), 1)
        close = float((dm[iu] <= FAMILY_RADIUS).mean())
        np.fill_diagonal(dm, np.inf)
        nn3 = np.sort(dm, axis=1)[:, :3].mean(axis=1)
        q75, q25 = np.percentile(nn3, [75, 25])
        split = cohort["split"].mode().iloc[0]
        print(f"  {e:<11}{len(ids):6d}{singl*100:8.1f}{maxfam:8d}"
              f"{close*100:8.2f}{q75-q25:9.4f}{nn3.std():8.4f}  {split}")
        mech_tbl.append([e, len(ids), singl, maxfam, close, q75 - q25,
                         float(nn3.std()), split])

    lines += ["## 4. Mechanism risk: does density have dynamic range?", "",
              "The GLCTLVAML failure (E20, E72) is visible label-free in the family",
              "structure, so the diagnostics are legitimate on the private cohorts.",
              "`nn3 IQR` is the spread of the quantity density actually ranks on --",
              "if it collapses, the ranking has nothing to work with.", "",
              "| epitope | rows | singleton % | largest family | close pairs % "
              "| nn3 IQR | nn3 sd | split |",
              "|---|---:|---:|---:|---:|---:|---:|---|"]
    for r in mech_tbl:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]*100:.1f} | {r[3]} | {r[4]*100:.2f} "
                     f"| {r[5]:.4f} | {r[6]:.4f} | {r[7]} |")
    lines.append("")

    # does nn3 spread actually predict per-epitope AUC on the public five?
    pub = [r for r in mech_tbl if r[0] in PUBLISHED]
    from scipy.stats import spearmanr
    for key, idx in (("nn3 IQR", 5), ("nn3 sd", 6), ("singleton %", 2),
                     ("close pairs %", 4)):
        x = [r[idx] for r in pub]
        rho_auc = spearmanr(x, [per_ep["D"][r[0]] for r in pub]).statistic
        rho_f = spearmanr(x, [fractions["D"][r[0]] for r in pub]).statistic
        print(f"  Spearman({key:<14}, D's AUC) = {rho_auc:+.3f}   "
              f"(, D's headroom fraction) = {rho_f:+.3f}")
    lines.append("Over the five public epitopes, against D:")
    lines.append("")
    lines.append("| diagnostic | ρ with AUC | ρ with headroom fraction |")
    lines.append("|---|---:|---:|")
    for key, idx in (("nn3 IQR", 5), ("nn3 sd", 6), ("singleton %", 2),
                     ("close pairs %", 4)):
        x = [r[idx] for r in pub]
        lines.append(
            f"| {key} | {spearmanr(x, [per_ep['D'][r[0]] for r in pub]).statistic:+.3f} "
            f"| {spearmanr(x, [fractions['D'][r[0]] for r in pub]).statistic:+.3f} |")
    lines.append("")

    # ---------- 5. does the ordering survive the worst case? ----------
    print("\n=== 5. does D > F > frozen survive an adversarial fraction? ===")
    print("  Each entry is given its own *worst* observed headroom fraction and")
    print("  each rival its own *best*, at the band midpoints. If the ordering")
    print("  holds there, it does not depend on which fraction is the right one.")
    mids = {e: sum(b) / 2 for e, b in PRIVATE_BANDS.items()}
    print(f"  {'entry':<9}{'mean f':>8}{'best f':>8}{'worst f':>9}"
          f"{'macro @mean':>13}{'@best':>8}{'@worst':>8}")
    worst_tbl = []
    for n in ENTRIES:
        fs = np.array(list(fractions[n].values()))
        row = []
        for f in (fs.mean(), fs.max(), fs.min()):
            row.append(float(np.mean([m + f * (1 - m) for m in mids.values()])))
        print(f"  {n:<9}{fs.mean():8.3f}{fs.max():8.3f}{fs.min():9.3f}"
              f"{row[0]:13.4f}{row[1]:8.4f}{row[2]:8.4f}")
        worst_tbl.append([n, fs.mean(), fs.max(), fs.min()] + row)
    best_of_rest = max(r[6] for r in worst_tbl if r[0] != "D")
    d_worst = [r[6] for r in worst_tbl if r[0] == "D"][0]
    print(f"\n  D at its worst fraction: {d_worst:.4f}")
    print(f"  the best rival at its best fraction: {best_of_rest:.4f}")
    print(f"  -> the ordering {'SURVIVES' if d_worst > best_of_rest else 'DOES NOT survive'}"
          " the adversarial assignment")

    lines += ["## 5. Does the ordering survive an adversarial fraction?", "",
              "Each entry is evaluated at its own mean, best and worst observed",
              "headroom fraction, at the band midpoints.", "",
              "| entry | mean f | best f | worst f | macro @mean | @best | @worst |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for r in worst_tbl:
        lines.append(f"| {r[0]} | {r[1]:.3f} | {r[2]:.3f} | {r[3]:.3f} | "
                     f"{r[4]:.4f} | {r[5]:.4f} | {r[6]:.4f} |")
    lines += ["",
              f"D at its worst fraction **{d_worst:.4f}** against the best rival at",
              f"its best **{best_of_rest:.4f}**: the ordering "
              f"**{'survives' if d_worst > best_of_rest else 'does not survive'}**.",
              ""]

    # ---------- 6. the structure-matched fraction, with a holdout ----------
    # Part 4 shows the private cohorts resemble TTDPSFLGRY, not GILGFVFTL or
    # GLCTLVAML: almost no families, mostly singletons. E74's headroom model
    # averages the fraction over all five public epitopes, which mixes in two
    # family-rich cohorts the private split does not look like. So: take the
    # fraction from the *structurally nearest* public epitope instead, and put
    # that model through the same leave-one-epitope-out test E74 used, so it is
    # not believed on the strength of the story.
    print("\n=== 6. a structure-matched fraction, under the same LOEO test ===")
    feat_names = ["singleton %", "log rows", "largest family",
                  "close pairs %", "nn3 IQR", "nn3 sd"]
    struct = {}
    for r in mech_tbl:
        struct[r[0]] = np.array([r[2], np.log(r[1]), np.log1p(r[3]),
                                 r[4], r[5], r[6]])
    pub_names = sorted(PUBLISHED)
    M = np.vstack([struct[e] for e in pub_names])
    mu, sd = M.mean(0), M.std(0) + 1e-12

    def z(e):
        return (struct[e] - mu) / sd

    print("  pairwise structural distance between the public epitopes "
          "(standardised):")
    print("  " + " " * 11 + "".join(f"{e[:4]:>8}" for e in pub_names))
    for a in pub_names:
        print(f"  {a:<11}" + "".join(
            f"{np.linalg.norm(z(a) - z(b)):8.2f}" for b in pub_names))

    print("\n  LOEO: predict each public epitope's margin, four models")
    print(f"  {'held out':<11}{'actual':>8}{'uniform':>9}{'headroom':>10}"
          f"{'matched':>9}{'  nearest'}")
    maes = {"uniform": [], "headroom": [], "matched": []}
    loeo_rows = []
    for e in pub_names:
        rest = [o for o in pub_names if o != e]
        base, head = PUBLISHED[e], 1.0 - PUBLISHED[e]
        actual = per_ep["D"][e] - base
        # uniform: the mean *margin* of the other four
        p_uni = float(np.mean([per_ep["D"][o] - PUBLISHED[o] for o in rest]))
        # headroom: the mean *fraction* of the other four, times this headroom
        p_head = float(np.mean([fractions["D"][o] for o in rest])) * head
        # matched: the fraction of the structurally nearest of the other four
        near = min(rest, key=lambda o: np.linalg.norm(z(e) - z(o)))
        p_match = fractions["D"][near] * head
        for k, v in (("uniform", p_uni), ("headroom", p_head),
                     ("matched", p_match)):
            maes[k].append(abs(v - actual))
        print(f"  {e:<11}{actual:+8.4f}{p_uni:+9.4f}{p_head:+10.4f}"
              f"{p_match:+9.4f}  {near}")
        loeo_rows.append([e, actual, p_uni, p_head, p_match, near])
    print(f"\n  {'MAE':<11}{'':8}{np.mean(maes['uniform']):9.4f}"
          f"{np.mean(maes['headroom']):10.4f}{np.mean(maes['matched']):9.4f}")
    winner = min(maes, key=lambda k: np.mean(maes[k]))
    print(f"  best held-out model: {winner}")

    print("\n  the private epitopes' structurally nearest public epitope:")
    priv_match = {}
    for e in PRIVATE_BANDS:
        near = min(pub_names, key=lambda o: np.linalg.norm(z(e) - z(o)))
        dist = np.linalg.norm(z(e) - z(near))
        priv_match[e] = near
        print(f"    {e:<11} -> {near:<11} (distance {dist:.2f}, "
              f"f = {fractions['D'][near]:.3f})")

    print("\n  private estimate under each fraction model:")
    print(f"  {'entry':<9}{'headroom (E74)':>16}{'structure-matched':>19}")
    final_rows = []
    for n in ENTRIES:
        fs = np.array(list(fractions[n].values()))
        e_head, e_match = [], []
        for e, (lo, hi) in PRIVATE_BANDS.items():
            mid = (lo + hi) / 2
            e_head.append(mid + fs.mean() * (1 - mid))
            e_match.append(mid + fractions[n][priv_match[e]] * (1 - mid))
        print(f"  {n:<9}{np.mean(e_head):16.4f}{np.mean(e_match):19.4f}")
        final_rows.append([n, float(np.mean(e_head)), float(np.mean(e_match))]
                          + [float(x) for x in e_match])
    print(f"\n  per-epitope under the matched model, D: "
          + "  ".join(f"{e.split('_')[0][:3]} {v:.3f}" for e, v in
                      zip(PRIVATE_BANDS, final_rows[1][3:])))

    lines += ["## 6. A structure-matched fraction, under the same LOEO test", "",
              "Part 4 shows the private cohorts resemble TTDPSFLGRY -- almost no",
              "families, overwhelmingly singletons -- and not the family-rich",
              "GILGFVFTL or GLCTLVAML. E74's headroom model averages the fraction",
              "over all five public epitopes, so it mixes in two cohorts the private",
              "split does not look like. Taking the fraction from the structurally",
              "nearest public epitope instead is put through E74's own",
              "leave-one-epitope-out test rather than believed on the story.", "",
              "| held out | actual margin | uniform | headroom | matched | nearest |",
              "|---|---:|---:|---:|---:|---|"]
    for r in loeo_rows:
        lines.append(f"| {r[0]} | {r[1]:+.4f} | {r[2]:+.4f} | {r[3]:+.4f} "
                     f"| {r[4]:+.4f} | {r[5]} |")
    lines += [f"| **MAE** | | **{np.mean(maes['uniform']):.4f}** "
              f"| **{np.mean(maes['headroom']):.4f}** "
              f"| **{np.mean(maes['matched']):.4f}** | |", "",
              f"Best held-out model: **{winner}**.", "",
              "The private epitopes' structurally nearest public epitope:", ""]
    for e, near in priv_match.items():
        lines.append(f"- {e} -> **{near}** "
                     f"(distance {np.linalg.norm(z(e) - z(near)):.2f}, "
                     f"D's f = {fractions['D'][near]:.3f})")
    lines += ["", "| entry | headroom (E74) | structure-matched |", "|---|---:|---:|"]
    for r in final_rows:
        lines.append(f"| {r[0]} | {r[1]:.4f} | **{r[2]:.4f}** |")
    lines.append("")

    REPORT.write_text("\n".join(lines) + "\n")
    print(f"\nwrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
